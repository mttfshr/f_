#!/usr/bin/env python3
"""
generate_menu.py -- generate package/patchers/f_modules.maxpat (the module menu) and the SIZES table
in package/javascript/f_addmod.js from src/f_modules/menu.py.

Replaces tools/rebuild_modules_menu.py and tools/append_nabla_menu.py (build_cleanup T020/T021): one
data file, one generator, one check.  Never hand-edit either generated file -- edit the data and
regenerate.  Follows build/generate_launch.py: validate loudly, write nothing on a failure, --check.

Usage:
    build/py.sh build/generate_menu.py            # write f_modules.maxpat and the SIZES block
    build/py.sh build/generate_menu.py --check    # exit 1 if either is stale or a check fails

Checks (any failure aborts, nothing is written):
    - the data is well formed: unique categories and modules, labels and flags of the right type
    - every menu module has package/patchers/f_<module>.maxpat
    - every shipped patcher is in the menu or in NOT_IN_MENU (with a reason), never both
    - the categories match the README Patches table (the table f_Launch is generated from):
      the same labels, the same order, the same members; README groups the menu does not show
      (Audio) hold only NOT_IN_MENU modules
    - a category whose label starts with a nabla holds vecfield modules only
    - every size override differs from the module's panel size (else it is stale)
    - every menu module has a presentation panel to take its size from
"""

