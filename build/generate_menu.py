def sizes_block(menu):
    rows = sizes_of(menu)
    lines = []
    for i, (m, (w, h)) in enumerate(rows):
        lines.append(f'    {chr(34) + m + chr(34) + ":":<18}[{w:>3}, {h:>3}]' + ("," if i < len(rows) - 1 else ""))
    return "\n".join([SIZES_BEGIN, "var SIZES = {"] + lines + ["};", SIZES_END])


def new_js(current, menu):
    if SIZES_BEGIN not in current or SIZES_END not in current:
        raise MenuError(f"{OUT_JS.name} has no `{SIZES_BEGIN}` ... `{SIZES_END}` markers")
    head, rest = current.split(SIZES_BEGIN, 1)
    _, tail = rest.split(SIZES_END, 1)
    return head + sizes_block(menu) + tail


def generate():
    menu = load_menu()
    groups = launch.parse_readme(README.read_text())
    validate(menu, groups)
    patcher_text = json.dumps(build_patcher(menu), indent=4)
    return patcher_text, new_js(OUT_JS.read_text(), menu)


def main(argv):
    check = "--check" in argv
    unknown = [a for a in argv if a != "--check"]
    if unknown:
        print(f"unknown argument(s): {unknown}", file=sys.stderr)
        return 2
    try:
        patcher_text, js_text = generate()
    except (MenuError, launch.LaunchError) as e:
        print(f"generate_menu: {e}", file=sys.stderr)
        return 1
    if check:
        stale = [p.name for p, text in ((OUT_PATCHER, patcher_text), (OUT_JS, js_text))
                 if not p.exists() or p.read_text() != text]
        if stale:
            print(f"generate_menu: stale: {', '.join(stale)} (run build/py.sh build/generate_menu.py)", file=sys.stderr)
            return 1
        print("generate_menu: f_modules.maxpat and f_addmod.js are up to date")
        return 0
    OUT_PATCHER.write_text(patcher_text)
    OUT_JS.write_text(js_text)
    print(f"wrote {OUT_PATCHER} and the SIZES block of {OUT_JS}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
