class MenuError(Exception):
    pass


def load_menu():
    spec = importlib.util.spec_from_file_location("f_modules_menu", MENU_DATA)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def panel_size(module):
    """The module's frame: its largest presentation panel, rounded half up to whole pixels."""
    path = PATCHERS_DIR / f"f_{module}.maxpat"
    patcher = json.loads(path.read_text())["patcher"]
    panels = [b["box"] for b in patcher["boxes"]
              if b["box"].get("maxclass") == "panel" and b["box"].get("presentation")]
    if not panels:
        raise MenuError(f"{path.name} has no presentation panel to take a size from")
    rect = max(panels, key=lambda b: b["presentation_rect"][2] * b["presentation_rect"][3])["presentation_rect"]
    return [math.floor(rect[2] + 0.5), math.floor(rect[3] + 0.5)]


def validate(menu, groups):
    problems = []
    cats = menu.CATEGORIES
    if not isinstance(cats, list) or not cats:
        raise MenuError("CATEGORIES must be a non-empty list")
    labels, modules = [], []
    for entry in cats:
        if not (isinstance(entry, tuple) and len(entry) == 2 and isinstance(entry[0], str) and isinstance(entry[1], list)):
            raise MenuError(f"a category must be (label, [entries]), not {entry!r}")
        label, items = entry
        labels.append(label)
        if not items:
            problems.append(f"empty category: {label!r}")
        shown = []
        for item in items:
            if not (isinstance(item, tuple) and len(item) == 3 and isinstance(item[0], str) and item[0]
                    and isinstance(item[1], str) and item[1] and isinstance(item[2], bool)):
                raise MenuError(f"a menu entry must be (display, module, vecfield: bool), not {item!r}")
            shown.append(item[0])
            modules.append(item[1])
            if label.startswith("\u2207") and not item[2]:
                problems.append(f"{item[1]}: in the nabla category {label!r} but not flagged vecfield")
        for d in sorted({x for x in shown if shown.count(x) > 1}):
            problems.append(f"{label!r}: two entries are shown as {d!r}")
    for lab in sorted({x for x in labels if labels.count(x) > 1}):
        problems.append(f"duplicate category: {lab!r}")
    for m in sorted({x for x in modules if modules.count(x) > 1}):
        problems.append(f"module listed twice: {m}")

    on_disk = {p.stem for p in PATCHERS_DIR.glob("*.maxpat")}
    for m in modules:
        if f"f_{m}" not in on_disk:
            problems.append(f"menu entry {m}: no package/patchers/f_{m}.maxpat")
    skip = menu.NOT_IN_MENU
    for name, reason in skip.items():
        if not (isinstance(reason, str) and reason.strip()):
            problems.append(f"NOT_IN_MENU[{name!r}] needs a reason")
        if name not in on_disk:
            problems.append(f"NOT_IN_MENU names {name}, which is not a shipped patcher")
        if name.removeprefix("f_") in modules:
            problems.append(f"{name} is both in the menu and in NOT_IN_MENU")
    for name in sorted(on_disk):
        if name.removeprefix("f_") not in modules and name not in skip:
            problems.append(f"patcher {name}.maxpat is neither in the menu nor in NOT_IN_MENU")

    # the README table and the menu describe the same grouping
    readme = {launch.tab_label(h): [n for n, _ in rows] for h, rows in groups}
    readme_order = [launch.tab_label(h) for h, _ in groups]
    shown_cats = [lab for lab in readme_order if lab in labels]
    for lab in labels:
        if lab not in readme:
            problems.append(f"menu category {lab!r} is not a README group (README groups: {readme_order})")
    if [lab for lab in labels if lab in readme] != shown_cats:
        problems.append(f"menu category order {labels} differs from the README's {shown_cats}")
    for label, items in cats:
        if label in readme:
            want, got = set(readme[label]) - set(skip), {f"f_{i[1]}" for i in items}
            for n in sorted(got - want):
                problems.append(f"{n} is in menu category {label!r} but in another README group")
            for n in sorted(want - got):
                problems.append(f"{n} is in README group {label!r} but not in that menu category")
    for lab, names in readme.items():
        if lab not in labels:
            for n in names:
                if n not in skip:
                    problems.append(f"{n} is in README group {lab!r}, which the menu does not show, "
                                    f"and is not in NOT_IN_MENU")

    overrides = menu.SIZE_OVERRIDES
    for m, spec in overrides.items():
        if m not in modules:
            problems.append(f"SIZE_OVERRIDES names {m}, which is not in the menu")
            continue
        if not (isinstance(spec, tuple) and len(spec) == 2 and isinstance(spec[1], str) and spec[1].strip()
                and isinstance(spec[0], list) and len(spec[0]) == 2 and all(isinstance(v, int) and v > 0 for v in spec[0])):
            problems.append(f"SIZE_OVERRIDES[{m!r}] must be ([w, h], reason)")
    if problems:
        raise MenuError("\n  ".join(["checks failed:"] + problems))

    for m in modules:                                    # sizes need the patchers to be readable
        panel = panel_size(m)
        if m in overrides and overrides[m][0] == panel:
            problems.append(f"SIZE_OVERRIDES[{m!r}] equals the panel size {panel}: stale override")
    if problems:
        raise MenuError("\n  ".join(["checks failed:"] + problems))


def sizes_of(menu):
    out = []
    for _, items in menu.CATEGORIES:
        for _, m, _ in items:
            out.append((m, menu.SIZE_OVERRIDES[m][0] if m in menu.SIZE_OVERRIDES else panel_size(m)))
    return out


def sorted_box(d):
    """Max saves every box with its keys sorted, nested dicts included; lists are left alone."""
    if isinstance(d, dict):
        return {k: sorted_box(d[k]) for k in sorted(d)}
    return d


