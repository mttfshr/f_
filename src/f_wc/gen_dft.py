"""
gen_dft.py -- writes f_wc's four separable-DFT stage codeboxes from f_vf_fluid's
template (src/f_vf_fluid/gen_dft.py), the third module on that one verified DFT
(f_ks's gen_dft.py is the same pattern). Only the comment header changes (module
name, stage number, packing note); the CODE lines are asserted identical to the
f_vf_fluid ones.

    fx  forward DFT along x     fy  forward DFT along y
    iy  inverse DFT along y     ix  inverse DFT along x  (+ real part + NaN/Inf guard)

Run:  python3 src/f_wc/gen_dft.py            (writes codebox_dft_*.gen next to it)

T020 decision record (2026-10-23): f_vf_fluid/gen_dft.py is the SHARED generator;
f_wc reuses it via this thin adapter, the same shape f_ks/gen_dft.py took. No third
copy: the template stays singular and every consumer's code lines are asserted
identical to it, so the three modules cannot drift apart (FR-002).

f_wc packs TWO real fields: R,G = Re,Im of E-hat; B,A = Re,Im of I-hat (both fields
have zero imaginary part on input, like f_vf_fluid's u,v packing -- the template
transforms two complex fields per pass, so ONE DFT chain carries BOTH WC fields).
Stage numbers: pass 0, fx 1, fy 2, spec 3, iy 4, ix 5, nl 6, enc 7.
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
FLUID = HERE.parent / "f_vf_fluid" / "gen_dft.py"
STAGE_NO = {"fx": 1, "fy": 2, "iy": 4, "ix": 5}


def _load_fluid():
    spec = importlib.util.spec_from_file_location("fluid_gen_dft", FLUID)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def code_lines(text):
    return [l for l in text.split("\n") if not l.lstrip().startswith("//")]


def render(fluid, key):
    name, text = fluid.render(key)
    old_stage = fluid.STAGES[key]["stage"]
    out = text.replace(f"f_vf_fluid stage {old_stage}", f"f_wc stage {STAGE_NO[key]}")
    out = out.replace("// Packing (float32 RGBA): R,G = Re,Im of u; B,A = Re,Im of v.",
                      "// Packing (float32 RGBA): R,G = Re,Im of the field E; B,A = Re,Im of the field I (two complex fields per pass, one chain for both).")
    out = out.replace("// GENERATED by gen_dft.py from one template -- edit the template, not this file.",
                      "// GENERATED by src/f_wc/gen_dft.py from f_vf_fluid's DFT template -- edit the template, not this file.")
    assert code_lines(out) == code_lines(text), f"{name}: code lines changed"
    assert "f_wc stage" in out and "f_vf_fluid" not in out.split("\n")[0]
    return name, out


def main():
    fluid = _load_fluid()
    for key in STAGE_NO:
        name, text = render(fluid, key)
        (HERE / name).write_text(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
