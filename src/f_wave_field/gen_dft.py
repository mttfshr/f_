"""
gen_dft.py -- writes f_wave_field's four separable-DFT stage codeboxes from f_vf_fluid's template
(src/f_vf_fluid/gen_dft.py), so the two modules share one verified DFT and cannot drift.
Only the comment header changes (module name, stage number, packing note); the CODE lines
are asserted identical to the f_vf_fluid ones.

    fx  forward DFT along x     fy  forward DFT along y
    iy  inverse DFT along y     ix  inverse DFT along x  (+ real part + NaN/Inf guard)

Run:  python3 src/f_wave_field/gen_dft.py            (writes codebox_dft_*.gen next to it)
f_wave_field packs TWO real fields, the f_vf_fluid packing the template was written for: forward input R = u, G = 0,
B = v, A = 0; spectral R,G = Re,Im of u-hat and B,A = Re,Im of v-hat. The inverse returns R = u, B = v.
Stage numbers: pass 0, fx 1, fy 2, spec 3, iy 4, ix 5, real 6, enc 7.
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
FLUID = HERE.parent / "f_vf_fluid" / "gen_dft.py"
STAGE_NO = {"fx": 1, "fy": 2, "iy": 4, "ix": 5}


def _load_fluid():
    spec = importlib.util.spec_from_file_location("fluid_gen_dft", FLUID)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def code_lines(text):
    return [l for l in text.split("\n") if not l.lstrip().startswith("//")]


def render(fluid, key):
    name, text = fluid.render(key)
    old_stage = fluid.STAGES[key]["stage"]
    out = text.replace(f"f_vf_fluid stage {old_stage}", f"f_wave_field stage {STAGE_NO[key]}")
    out = out.replace("// GENERATED by gen_dft.py from one template -- edit the template, not this file.",
                      "// GENERATED by src/f_wave_field/gen_dft.py from f_vf_fluid's DFT template -- edit the template, not this file.")
    assert code_lines(out) == code_lines(text), f"{name}: code lines changed"
    assert "f_wave_field stage" in out and "f_vf_fluid" not in out.split("\n")[0]
    return name, out


def main():
    fluid = _load_fluid()
    for key in STAGE_NO:
        name, text = render(fluid, key)
        (HERE / name).write_text(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
