"""
gen_dft.py -- writes f_vf_immiscible's four separable-DFT stage codeboxes from f_vf_fluid's template
(src/f_vf_fluid/gen_dft.py), so the modules share one verified DFT and cannot drift (plan ADR-4, T010).
Only the comment header changes (module name, stage number, packing note); the CODE lines are
asserted identical to the f_vf_fluid ones, as src/f_ks/gen_dft.py does.

    fx  forward DFT along x     fy  forward DFT along y
    iy  inverse DFT along y     ix  inverse DFT along x  (+ real part + NaN/Inf guard)

Run:  python3 src/f_vf_immiscible/gen_dft.py       (writes codebox_dft_*.gen next to it)
f_vf_immiscible packs phi and phi^3 as the two complex fields of one chain: forward input R = phi,
B = phi^3 (G, A = 0 are the imaginary parts); spectral R,G = Re,Im phi-hat and B,A = Re,Im (phi^3)^.
After the spec stage B,A are 0, so the inverse returns R = phi and B = 0 (the guard in ix zaps
non-finite values; the module's `pass` stage reads only R).
Stage numbers (plan ADR-1): inab 0, hold 1, pass 2, adv 3, fx 4, fy 5, spec 6, iy 7, ix 8, enc 9.
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
FLUID = HERE.parent / "f_vf_fluid" / "gen_dft.py"
STAGE_NO = {"fx": 4, "fy": 5, "iy": 7, "ix": 8}


def _load_fluid():
    spec = importlib.util.spec_from_file_location("fluid_gen_dft", FLUID)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def code_lines(text):
    return [l for l in text.split("\n") if not l.lstrip().startswith("//")]


def render(fluid, key):
    name, text = fluid.render(key)
    old_stage = fluid.STAGES[key]["stage"]
    out = text.replace(f"f_vf_fluid stage {old_stage}", f"f_vf_immiscible stage {STAGE_NO[key]}")
    out = out.replace("// Packing (float32 RGBA): R,G = Re,Im of u; B,A = Re,Im of v.",
                      "// Packing (float32 RGBA): R,G = Re,Im of phi; B,A = Re,Im of phi^3 (forward input R = phi, B = phi^3).")
    out = out.replace("// GENERATED by gen_dft.py from one template -- edit the template, not this file.",
                      "// GENERATED by src/f_vf_immiscible/gen_dft.py from f_vf_fluid's DFT template -- edit the template, not this file.")
    assert code_lines(out) == code_lines(text), f"{name}: code lines changed"
    assert "f_vf_immiscible stage" in out and "f_vf_fluid" not in out.split("\n")[0]
    return name, out


def main():
    fluid = _load_fluid()
    for key in STAGE_NO:
        name, text = render(fluid, key)
        (HERE / name).write_text(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
