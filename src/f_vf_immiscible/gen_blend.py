"""
gen_blend.py -- writes codebox_adv.gen and codebox_enc.gen for f_vf_immiscible from ONE blend block
(plan ADR-3, T013), so the blend that advects phi (adv, solver grid) and the blend that is output
(enc, render size) cannot drift apart. test_immiscible_static.py asserts the two copies are identical.

G2 (decided by Matt 2026-10-27, T007): the PLAIN convex blend. The interface-aware rule raised the
peak divergence in every band tried and is not in the module.

Run:  python3 src/f_vf_immiscible/gen_blend.py       (writes codebox_adv.gen and codebox_enc.gen next to it)
Mirrors: immiscible_mirror.adv(), .enc(), .blend_vel(mode 0), .blend_weight().
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

BLEND = """\
// ---- blend begin (plain convex, G2; identical in codebox_adv.gen and codebox_enc.gen) ----
bw = clamp((ph + 1) * 0.5, 0, 1);
ux = mix(uax, ubx, bw);
uy = mix(uay, uby, bw);
// ---- blend end ----
"""

ADV = """\
// codebox_adv.gen -- f_vf_immiscible stage 3: blend the two velocities by phi, backward-advect phi by the
// blend, inject, clamp, pack phi and phi^3 for the DFT chain. 256x256 float32.
// GENERATED by src/f_vf_immiscible/gen_blend.py -- edit the generator, not this file.
// Mirror: tests/modules/immiscible/immiscible_mirror.adv().
//
// Inputs: in1 = phi state from `pass` (R = phi; the HOT inlet, plan ADR-1 amended 2026-10-27 so the
// cold packed velocities have always landed when `pass` fires this stage), in2 = packed velocities from
// `inab` (R,G = uA, B,A = uB, decoded), in3 = phi source texture at render resolution (via vs_inState).
// Output: R = phi, B = phi^3 (G, A = 0 are the imaginary parts for the DFT chain).
//   - phi is read with a manual 4-tap bilinear whose integer indices wrap with wrap(): the domain is
//     periodic and hardware sample() clamps its neighbour tap (f_vf_fluid carried finding)
//   - injection: phi += inject * luma(source) * (1 - phi): bounded, phase B only, no effect at phi = 1.
//     The source is averaged over a taps x taps grid of hardware taps in normalized offsets, like inab.
//     src_phi = 0 (inlet unconnected) disables it
//   - the clamp bound 1.25 is PHI_CLAMP of the mirror (T004: observed |phi| <= 1.03); a safety net only
//   - freeze = 1 passes phi through unchanged (no advection, no injection, no clamp), still packed
//   - components are accessed inline on nearest()/sample(), never on a stored vec
Param dt(0.01);
Param inject(0.2);
Param taps(2);
Param freeze(0);
Param src_phi(0);

N = 256;
ph = nearest(in1, norm).x;
uax = nearest(in2, norm).x;
uay = nearest(in2, norm).y;
ubx = nearest(in2, norm).z;
uby = nearest(in2, norm).w;
{blend}
// departure point (continuous texel coordinates), periodic bilinear read of phi
fx = (norm.x - ux * dt) * N - 0.5;
fy = (norm.y - uy * dt) * N - 0.5;
x0 = floor(fx);
y0 = floor(fy);
tx = fx - x0;
ty = fy - y0;
xa = wrap(x0, 0, N);
xb = wrap(x0 + 1, 0, N);
ya = wrap(y0, 0, N);
yb = wrap(y0 + 1, 0, N);
p00 = vec((xa + 0.5) / N, (ya + 0.5) / N);
p10 = vec((xb + 0.5) / N, (ya + 0.5) / N);
p01 = vec((xa + 0.5) / N, (yb + 0.5) / N);
p11 = vec((xb + 0.5) / N, (yb + 0.5) / N);
ap = mix(mix(nearest(in1, p00).x, nearest(in1, p10).x, tx), mix(nearest(in1, p01).x, nearest(in1, p11).x, tx), ty);

// injection: luma of the source through the tap grid
gate = switch(src_phi >= 0.5, 1, 0);
tn = switch(gate >= 0.5, max(1, floor(taps)), 1);
sr = 0;
sg = 0;
sb = 0;
for (a = 0; a < tn; a += 1) {{
  ox = ((a + 0.5) / tn - 0.5) / N;
  for (b = 0; b < tn; b += 1) {{
    oy = ((b + 0.5) / tn - 0.5) / N;
    sr += sample(in3, vec(norm.x + ox, norm.y + oy)).x;
    sg += sample(in3, vec(norm.x + ox, norm.y + oy)).y;
    sb += sample(in3, vec(norm.x + ox, norm.y + oy)).z;
  }}
}}
luma = (0.2126 * sr + 0.7152 * sg + 0.0722 * sb) / (tn * tn);
newp = ap + inject * luma * (1 - ap) * gate;
newp = clamp(newp, -1.25, 1.25);
newp = switch(freeze >= 0.5, ph, newp);
out1 = vec(newp, 0, newp * newp * newp, 0);
"""

ENC = """\
// codebox_enc.gen -- f_vf_immiscible stage 9: upsample phi and both velocities to the render size, blend,
// encode both outlets, apply the bypass gate. Runs at RENDER resolution.
// GENERATED by src/f_vf_immiscible/gen_blend.py -- edit the generator, not this file.
// Mirror: tests/modules/immiscible/immiscible_mirror.enc().
//
// Inputs: in1 = `r draw` bang (unused; triggers every frame and gives this pix the render-context size),
// in2 = packed velocities from `inab` (256x256, cold), in3 = phi state from `ix` (R = phi, 256x256).
// Outputs: out1 = phi as a grey scalar texture w = (phi + 1) / 2 in R, G, B with A = 1 (G4);
//          out2 = the blended velocity as an f_vecfield: R,G = 0.5 + 0.5 * clamp(u, -1, 1), B = 0.5, A = 1.
//   - everything is read with a manual periodic 4-tap (works for any output size, including smaller than
//     256 where hardware sample() would snap)
//   - bypass_gate = 1 mixes BOTH outlets to their own-kind neutral (0.5, 0.5, 0.5, 1): out1 mid grey,
//     out2 the neutral vecfield (G5, decided 2026-10-27; the solver keeps running)
//   - Param is bypass_gate, never `bypass` (native pix attribute)
Param bypass_gate(0);

N = 256;
fx = norm.x * N - 0.5;
fy = norm.y * N - 0.5;
x0 = floor(fx);
y0 = floor(fy);
tx = fx - x0;
ty = fy - y0;
xa = wrap(x0, 0, N);
xb = wrap(x0 + 1, 0, N);
ya = wrap(y0, 0, N);
yb = wrap(y0 + 1, 0, N);
p00 = vec((xa + 0.5) / N, (ya + 0.5) / N);
p10 = vec((xb + 0.5) / N, (ya + 0.5) / N);
p01 = vec((xa + 0.5) / N, (yb + 0.5) / N);
p11 = vec((xb + 0.5) / N, (yb + 0.5) / N);
ph = mix(mix(nearest(in3, p00).x, nearest(in3, p10).x, tx), mix(nearest(in3, p01).x, nearest(in3, p11).x, tx), ty);
uax = mix(mix(nearest(in2, p00).x, nearest(in2, p10).x, tx), mix(nearest(in2, p01).x, nearest(in2, p11).x, tx), ty);
uay = mix(mix(nearest(in2, p00).y, nearest(in2, p10).y, tx), mix(nearest(in2, p01).y, nearest(in2, p11).y, tx), ty);
ubx = mix(mix(nearest(in2, p00).z, nearest(in2, p10).z, tx), mix(nearest(in2, p01).z, nearest(in2, p11).z, tx), ty);
uby = mix(mix(nearest(in2, p00).w, nearest(in2, p10).w, tx), mix(nearest(in2, p01).w, nearest(in2, p11).w, tx), ty);
{blend}
r = 0.5 + 0.5 * clamp(ux, -1, 1);
g = 0.5 + 0.5 * clamp(uy, -1, 1);
out1 = vec(mix(bw, 0.5, bypass_gate), mix(bw, 0.5, bypass_gate), mix(bw, 0.5, bypass_gate), 1);
out2 = vec(mix(r, 0.5, bypass_gate), mix(g, 0.5, bypass_gate), 0.5, 1);
"""


def render():
    return {"codebox_adv.gen": ADV.format(blend=BLEND.rstrip("\n")),
            "codebox_enc.gen": ENC.format(blend=BLEND.rstrip("\n"))}


def main():
    for name, text in render().items():
        (HERE / name).write_text(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
