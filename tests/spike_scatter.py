"""
spike_scatter.py -- scatter feasibility spike, stages S0-S2 (ideas/optics_map.md, ideas/f_lumia.md).

A record, not a regression gate (it matches no runner and is not registered in benchdeps): it drives
the module bench with tests/bench/spike_scatter.maxpat (generated by make_spike_scatter.py) and
prints what the GPU did against a NumPy emulation of the shader and against the photon-counting
ground truth from scratch/caustic_fidelity.py.

  S0  identity (d = 0, gradient source): does a point grid in a float32 node reproduce its source?
      Also reveals the net vertical orientation of node capture vs the pix chain.
  S0b a uniform field shifts the gradient: identifies BOTH flips (texture upload, capture readback).
  S1  float accumulation: 4096 points land on one pixel. Does the float32 capture hold 4096, or clamp?
  S2  a real glass field vs the NumPy scatter of the same lattice, and vs the photon-counting truth,
      at 0.6, 1.0 and 3.5 x d*.

Needs Max with the module bench open (this script reopens it if not).  Run:
  uv run --no-project --with numpy --with matplotlib python3 tests/spike_scatter.py
"""
