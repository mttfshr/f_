def ensure_bench():
    if not bc.ping(2.0, ports=bc.MODULE_PORTS):
        print("module bench not open: reopening (Max comes to the front)")
        bc.reopen(wait=40.0, ports=bc.MODULE_PORTS, patch="bench_module.maxpat")


def run(src, field, params, timeout_ms=90000, settle=SETTLE, warmup=WARMUP,
        module="spike_scatter.maxpat", n_out=1, multi=False):
    """One job. Returns (result, {tag: out1 RGBA}), or {tag: {k: RGBA}} with multi=True. tag 'base' =
    defaults, before any param is sent; tag 'bypassed' = after all params (the module bench's
    timeline names it that way)."""
    job, job_dir = bc.new_job("module", warmup=warmup, settle=settle, timeout_ms=timeout_ms)
    job["wrapper"] = f"mjob_{job['id']}.maxpat"
    job["inputs"] = []
    for i, arr in enumerate((src, field)):
        fn = f"in{i + 1}.jxf"
        jxf.write_rgba(job_dir / fn, np.asarray(arr, F32))
        job["inputs"].append(fn)
    job["params"] = params
    job["readback"], job["controls"] = {}, []
    wrapper = bc.BENCH_DIR / job["wrapper"]
    wrapper.write_text(json.dumps(make_wrapper(module, 2, n_out), indent=2))
    result = bc.run_job(job, job_dir, ports=bc.MODULE_PORTS)
    for old in bc.BENCH_DIR.glob("mjob_*.maxpat"):
        if old != wrapper:
            old.unlink()
    out = {}
    for tag, ks in (result.get("outputs") or {}).items():
        if multi:
            out[tag] = {k: jxf.read_rgba(job_dir / f"{tag}_out{k}.jxf") for k in ks}
        elif 1 in ks:
            out[tag] = jxf.read_rgba(job_dir / f"{tag}_out1.jxf")
    return result, out


def report(result, label):
    errs = result.get("errors") or []
    print(f"  [{label}] status={result.get('status')} frames={result.get('frames_rendered')} "
          f"elapsed={result.get('elapsed_ms')} ms errors={len(errs)}")
    for e in errs[:6]:
        print(f"      max error: {e[:200]}")


# ------------------------------------------------------- NumPy shader emulation
def flip(a, on):
    return a[::-1] if on else a


def ref_scatter(src, field, d, n, w, up_flip=False, out_flip=False, r=R, fy=1.0):
    """What the shader should do. Lattice u_i = i/(n-1) (a plane gridshape spans [-1, 1] inclusive),
    textures sampled bilinear/clamp, each point splatted with a bilinear (tent) footprint, additive.
    (A plain size-1 GL point is round and deposits only if its centre is within 0.5 px of a pixel
    centre: it aliased against the lattice and lost ~21% of the energy, spike S1.)
    up_flip: texture memory = flipud(matrix); out_flip: matrix = flipud(framebuffer).
    fy multiplies the field's Y (the shader's `fy` uniform)."""
    t = (np.arange(n, dtype=np.float64) / (n - 1)).astype(F32)
    U, V = np.meshgrid(t, t)
    f = (g.sample(flip(field, up_flip), U, V)[..., :2] - F32(0.5)) * F32(2.0)
    X = U + F32(d) * f[..., 0]
    Y = V + F32(d) * f[..., 1] * F32(fy)
    # tent (bilinear) splat, as the fragment shader does: pixel k gets 1 - |k + 0.5 - x*r| (if > 0)
    # a point whose CENTRE is outside the viewport is clipped whole (GL clips a point by its centre)
    centre_in = (X >= 0) & (X <= 1) & (Y >= 0) & (Y <= 1)
    fx, fyy = X * F32(r) - F32(0.5), Y * F32(r) - F32(0.5)
    x0, y0 = np.floor(fx), np.floor(fyy)
    tx, ty = fx - x0, fyy - y0
    x0, y0 = x0.astype(np.int64), y0.astype(np.int64)
    val = g.sample(flip(src, up_flip), U, V) * F32(w)
    img = np.zeros((r, r, 4))
    for ox, oy, wt in ((0, 0, (1 - tx) * (1 - ty)), (1, 0, tx * (1 - ty)),
                       (0, 1, (1 - tx) * ty), (1, 1, tx * ty)):
        px, py = x0 + ox, y0 + oy
        ok = centre_in & (px >= 0) & (px < r) & (py >= 0) & (py < r)
        flat = (py * r + px)[ok]
        for c in range(4):
            img[..., c] += np.bincount(flat, weights=(val[..., c] * wt)[ok].astype(np.float64),
                                       minlength=r * r).reshape(r, r)
    return flip(img, out_flip).astype(F32)


def combos():
    return [(u, o) for u in (False, True) for o in (False, True)]


def rel_err(a, b, ch=slice(0, 3)):
    a, b = a[..., ch].astype(np.float64), b[..., ch].astype(np.float64)
    return float(np.abs(a - b).mean() / max(np.abs(b).mean(), 1e-12))


# ------------------------------------------------------------------ test inputs
def gradient_src(n=TEX):
    nx, ny, _, _ = g.grid(n, n)
    a = np.zeros((n, n, 4), F32)
    a[..., 0], a[..., 1], a[..., 2], a[..., 3] = nx, ny, nx * ny, 1.0
    return a


def uniform_field(fx, fy, n=TEX):
    a = np.zeros((n, n, 4), F32)
    a[..., 0], a[..., 1], a[..., 3] = fx / 2 + 0.5, fy / 2 + 0.5, 1.0
    return a


def white(n=TEX):
    return np.ones((n, n, 4), F32)


def stage_s0_s0b():
    print("\n== S0 / S0b: identity and orientation ==")
    src, fld = gradient_src(), uniform_field(0.3, 0.5)
    result, out = run(src, fld, [["d", 0.25], ["weight", 1.0]])
    report(result, "S0/S0b")
    if "base" not in out or "bypassed" not in out:
        print("  FAIL: captures missing", list(out))
        return None
    base, shifted = out["base"], out["bypassed"]
    print(f"  base capture: shape {base.shape}, mean RGB {base[..., :3].mean(axis=(0, 1)).round(3)}, "
          f"max {base[..., :3].max():.3f}")
    print("  S0 identity (d=0, n=256, weight=1): relative error vs NumPy emulation, per (up_flip, out_flip):")
    for u, o in combos():
        print(f"     up={int(u)} out={int(o)}  rel_err = "
              f"{rel_err(base, ref_scatter(src, fld, 0.0, 256, 1.0, u, o)):.4f}")
    print("  S0b shift (d=0.25, F=(0.3,0.5), n=256):")
    best, errs = None, {}
    for u, o in combos():
        e = errs[(u, o)] = rel_err(shifted, ref_scatter(src, fld, 0.25, 256, 1.0, u, o))
        print(f"     up={int(u)} out={int(o)}  rel_err = {e:.4f}")
        if best is None or e < errs[best]:
            best = (u, o)
    second = sorted(errs.values())[1]
    print(f"  best = up_flip {int(best[0])}, out_flip {int(best[1])} "
          f"(error {errs[best]:.4f} vs runner-up {second:.4f}: "
          f"{'distinct' if second > 3 * max(errs[best], 1e-4) else 'AMBIGUOUS'})")
    return best


def stage_s1(flips):
    print("\n== S1: float32 accumulation (4096 points, one pixel) ==")
    up, out_flip = flips
    n, tx, ty = 64, (100 + 0.5) / R, (150 + 0.5) / R          # target at a pixel centre
    nx, ny, _, _ = g.grid(TEX, TEX)
    gl_field = np.zeros((TEX, TEX, 4), F32)                    # F(u) = T - u, in GL space, d = 1
    gl_field[..., 0] = (tx - nx) / 2 + 0.5
    gl_field[..., 1] = (ty - ny) / 2 + 0.5
    gl_field[..., 3] = 1.0
    field_matrix = flip(gl_field, up)                          # matrix whose upload is gl_field
    result, out = run(white(), field_matrix, [["n", n], ["d", 1.0], ["weight", 1.0]])
    report(result, "S1")
    if "bypassed" not in out:
        print("  FAIL: capture missing")
        return
    img = out["bypassed"][..., 0]
    pk = np.unravel_index(np.argmax(img), img.shape)
    expect_row = (R - 1 - 150) if out_flip else 150
    print(f"  peak value {img.max():.1f} at (row {pk[0]}, col {pk[1]}); expected {n * n} at "
          f"(row {expect_row}, col 100); total over image {img.sum():.1f}")
    verdict = "PASS: float32 accumulates beyond 1.0" if img.max() > 1.5 else "FAIL: clamped near 1"
    exact = abs(float(img.max()) - n * n) < 0.5
    print(f"  {verdict}; peak {'equals' if exact else 'does NOT equal'} N^2 exactly")
    mult = float(img.sum()) / (n * n)
    print(f"  point multiplicity (total / N^2) = {mult:.4f}"
          f"{'' if abs(mult - 1) < 1e-3 else '  <-- NOT 1: the drawable emits each vertex more than once; weight must be divided by this'}")
    return mult


def stage_s2(flips, mult=1.0, fracs=(0.6, 1.0, 3.5)):
    print("\n== S2: real glass field vs NumPy scatter and photon-counting truth ==")
    n = int(os.environ.get("SPIKE_N", "1536"))
    w = (R / n) ** 2 / mult
    fy = -1.0 if tuple(flips) == (True, True) else 1.0
    print(f"  n={n}, weight={w:.5f} (multiplicity {mult:.3f}), fy={fy:+.0f} (flips {flips})")
    tex, dstar = cf.field_texture(), cf.first_fold_distance()
    tex512 = np.asarray(tex, F32)
    rows = []
    for fr in fracs:
        d = fr * dstar
        result, out = run(white(), tex512, [["n", n], ["d", d], ["weight", w], ["fy", fy]])
        report(result, f"S2 d={fr}d*")
        if "bypassed" not in out:
            print("  FAIL: capture missing")
            continue
        gpu = out["bypassed"]
        ref_found = ref_scatter(white(), tex512, d, n, w, *flips, fy=fy)
        ref_phys = ref_scatter(white(), tex512, d, n, w, False, False, fy=1.0)
        truth = cf.truth(d)
        mask = cf.interior(d)
        modl = cf.down(cf.module_caustic(tex512, cf.white(), d))
        a = gpu[..., 0].astype(np.float64)
        row = {"d": fr,
               "sum": (float(a.sum()), float(ref_found[..., 0].sum())),
               "r_vs_ref_found": cf.pearson(a[mask], ref_found[..., 0][mask]),
               "r_vs_ref_physical": cf.pearson(a[mask], ref_phys[..., 0][mask]),
               "r_vs_truth": cf.pearson(a[mask], truth[mask]),
               "iou_vs_truth": cf.top_iou(a[mask], truth[mask]),
               "r_module_vs_truth": cf.pearson(modl[mask], truth[mask]),
               "iou_module_vs_truth": cf.top_iou(modl[mask], truth[mask]),
               "max": float(a.max())}
        rows.append((row, a, ref_found[..., 0], truth, modl))
        print(f"  d={fr}d*: sum GPU {row['sum'][0]:.0f} vs ref {row['sum'][1]:.0f} | "
              f"r(GPU, NumPy scatter, detected flips) = {row['r_vs_ref_found']:.4f} | "
              f"r(GPU, NumPy scatter, physical convention) = {row['r_vs_ref_physical']:.4f}")
        print(f"          r(GPU, truth) = {row['r_vs_truth']:.3f}, top-8% IoU {row['iou_vs_truth']:.3f}   "
              f"[module mirror: r {row['r_module_vs_truth']:.3f}, IoU {row['iou_module_vs_truth']:.3f}]   "
              f"peak value {row['max']:.2f}")
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        names = ["truth (photon count)", "GPU scatter", "NumPy scatter", "module (gather)"]
        fig, ax = plt.subplots(4, len(rows), figsize=(2.2 * len(rows), 8.8), squeeze=False)
        for c, (row, a, rf, tr, md) in enumerate(rows):
            for r_, img in enumerate((tr, a, rf, md)):
                ax[r_, c].imshow(img, cmap="inferno", vmin=0, vmax=np.percentile(img, 99.5))
                ax[r_, c].set_xticks([])
                ax[r_, c].set_yticks([])
                if r_ == 0:
                    ax[r_, c].set_title(f"d = {row['d']} d*")
                if c == 0:
                    ax[r_, c].set_ylabel(names[r_], fontsize=8)
        fig.tight_layout()
        fp = HERE.parent / "scratch" / "scatter_spike_s2.png"
        fig.savefig(fp, dpi=70)
        print(f"  figure: {fp}")
    except ImportError:
        pass


def stage_s3_cost(flips):
    """Frame-period slope: the bench paces at ~16.7 ms (60 fps), so a result near that only says
    'within budget'; the slope rises once the GPU needs longer. Two job lengths per config
    (settle 12 and 60: 144 frames apart) cancel the one-off lattice build."""
    print("\n== S3a: cost (ms per frame from the slope between two job lengths; cap ~16.7) ==")
    dstar = cf.first_fold_distance()
    tex512 = np.asarray(cf.field_texture(), F32)
    nx, ny, _, _ = g.grid(TEX, TEX)
    tx, ty = (100 + 0.5) / R, (150 + 0.5) / R                  # worst case: every point on one pixel
    gl = np.zeros((TEX, TEX, 4), F32)
    gl[..., 0], gl[..., 1], gl[..., 3] = (tx - nx) / 2 + 0.5, (ty - ny) / 2 + 0.5, 1.0
    worst = flip(gl, flips[0])
    cases = [("glass 3.5d*", tex512, 3.5 * dstar, -1.0 if tuple(flips) == (True, True) else 1.0),
             ("worst: all points on one pixel", worst, 1.0, 1.0)]
    configs = [(64, 256), (1024, 256), (2048, 256), (1024, 1024), (2048, 1024), (2560, 1024)]
    for label, fld, d, fy in cases:
        print(f"  -- {label}")
        for n, r in configs:
            params = [["n", n], ["r", r], ["d", d], ["weight", 1.0], ["fy", fy]]
            try:
                (r1, _), (r2, _) = run(white(), fld, params, settle=12), run(white(), fld, params, settle=60)
            except Exception as e:                              # a stall or timeout is a result too
                print(f"     n={n:5d} ({n * n / 1e6:5.2f} M points) capture {r}x{r}: FAILED {type(e).__name__}: {e}")
                continue
            df = r2["frames_rendered"] - r1["frames_rendered"]
            ms = (r2["elapsed_ms"] - r1["elapsed_ms"]) / df if df > 0 else float("nan")
            errs = len(r1.get("errors") or []) + len(r2.get("errors") or [])
            print(f"     n={n:5d} ({n * n / 1e6:5.2f} M points) capture {r:4d}^2: {ms:6.2f} ms/frame"
                  f"{'  (at the 60 fps cap)' if ms < 17.5 else '  <-- over budget'}   errors {errs}")


def stage_s2b_density(flips, mult=1.0, fracs=(1.0, 3.5), ns=(256, 384, 512, 768, 1024, 1536)):
    """Quality vs point density: how many points per pixel does the caustic need?"""
    print("\n== S2b: quality vs point density (capture 256^2; points per pixel = n^2 / 256^2) ==")
    fy = -1.0 if tuple(flips) == (True, True) else 1.0
    dstar = cf.first_fold_distance()
    tex512 = np.asarray(cf.field_texture(), F32)
    for fr in fracs:
        d = fr * dstar
        truth, mask = cf.truth(d), cf.interior(d)
        print(f"  -- d = {fr} d*   (photon-count truth has ~144 samples/bin: its own noise limits r to ~0.99+)")
        for n in ns:
            w = (R / n) ** 2 / mult
            result, out = run(white(), tex512, [["n", n], ["d", d], ["weight", w], ["fy", fy]])
            if "bypassed" not in out:
                print(f"     n={n:5d}: capture missing")
                continue
            a = out["bypassed"][..., 0].astype(np.float64)
            print(f"     n={n:5d}  {n * n / R ** 2:5.1f} pts/px  {n * n / 1e6:5.2f} M pts:  "
                  f"r(GPU, truth) = {cf.pearson(a[mask], truth[mask]):.4f}   "
                  f"top-8% IoU = {cf.top_iou(a[mask], truth[mask]):.3f}   peak {a.max():.1f}")


def stage_s3b_lag(flips, jobs=8):
    """Same-frame ordering. spike_scatter_chain.maxpat runs an upstream pix whose uniform field encodes a
    free-running frame counter c (0..39) as F.x = 0.0125 * c. In ONE capture we read c back from (a) that
    pix, (b) a plain pix->pix reference, (c) the scatter output, whose mean shifts with the field it
    actually used (decoded through the NumPy emulation). The differences are the relative lags, in frames."""
    print("\n== S3b: frame lag of pix -> node(mesh) -> capture vs pix -> pix (counter decode) ==")
    fy = -1.0 if tuple(flips) == (True, True) else 1.0
    n, d = 512, 0.25
    w = (R / n) ** 2
    src, fld = gradient_src(), uniform_field(0.0, 0.0)
    m = slice(40, 216)
    cal = np.array([float(ref_scatter(src, uniform_field(0.0125 * c, 0.0), d, n, w, flips[0], flips[1],
                                      fy=fy)[m, m, 0].mean()) for c in range(40)])
    print(f"  decode table: mean R of the scatter for c = 0, 1, 39: {cal[0]:.4f}, {cal[1]:.4f}, {cal[39]:.4f}"
          f" (step {cal[1] - cal[0]:+.5f} per frame; the capture noise floor is far below that)")

    def wrap(v):                                     # counter differences, modulo 40, into -20..19
        return int((v + 20) % 40 - 20)

    lags_sc, lags_ref = [], []
    for k in range(jobs):
        params = [["n", n], ["d", d], ["weight", w], ["fy", fy]]
        result, out = run(src, fld, params, settle=6, warmup=30 + k, module="spike_scatter_chain.maxpat",
                          n_out=3, multi=True)
        report(result, f"S3b job {k}")
        o = out.get("bypassed")
        if not o or not all(i in o for i in (1, 2, 3)):
            print("     FAIL: captures missing", None if not o else sorted(o))
            continue
        c_sc = int(np.argmin(np.abs(cal - float(o[1][m, m, 0].mean()))))
        c_up = int(round(2 * (float(o[2][..., 0].mean()) - 0.5) / 0.0125))
        c_ref = int(round(2 * (float(o[3][..., 0].mean()) - 0.5) / 0.0125))
        lags_sc.append(wrap(c_up - c_sc))
        lags_ref.append(wrap(c_up - c_ref))
        print(f"     job {k}: counter seen by upstream pix = {c_up:2d}, by pix->pix reference = {c_ref:2d}, "
              f"by scatter output = {c_sc:2d}   -> lag vs upstream pix: reference {lags_ref[-1]:+d}, scatter {lags_sc[-1]:+d} frames")
    if lags_sc:
        print(f"  summary over {len(lags_sc)} captures: pix->pix reference lag values {sorted(set(lags_ref))}; "
              f"scatter lag values {sorted(set(lags_sc))} (frames behind the upstream pix)")


CAP_MS = 1000.0 / 60.0          # the bench's frame pacing: a pass cheaper than this is invisible to it


def _period_ms(n, r, d, fy, psize, snap=0.0, h=1.0, reps=1):
    """Frame period in ms (one scatter pass, one mesh): slope between a short and a long job, which
    cancels the one-off lattice build. Returns (list of ms per rep, total errors). Values at or under
    the cap only mean 'within budget'; above it they are the pass's real cost."""
    params = [["r", r], ["psize", psize], ["snap", snap], ["h", h], ["d", d],
              ["weight", (r / n) ** 2], ["fy", fy], ["n", n]]
    out, errs = [], 0
    for _ in range(reps):
        r1, _o1 = run(white(), TEX_FIELD, params, settle=12, timeout_ms=300000, warmup=12)
        r2, _o2 = run(white(), TEX_FIELD, params, settle=48, timeout_ms=300000, warmup=12)
        df = r2["frames_rendered"] - r1["frames_rendered"]
        out.append((r2["elapsed_ms"] - r1["elapsed_ms"]) / df if df > 0 else float("nan"))
        errs += len(r1.get("errors") or []) + len(r2.get("errors") or [])
    return out, errs


def stage_s4_sweep(flips):
    """S4: cost of ONE pass above the 60 fps cap, by raising the lattice size n in a single mesh.
    Density is at its worst here (up to 16 points per pixel), so ms per million points is a conservative
    upper bound for lower densities. Two variants: the current size-3 footprint, and corner-snapped size 2."""
    global TEX_FIELD
    TEX_FIELD = np.asarray(cf.field_texture(), F32)
    fy = -1.0 if tuple(flips) == (True, True) else 1.0
    d = 3.5 * cf.first_fold_distance()
    print(f"\n== S4: one-pass cost above the cap (single mesh; cap {CAP_MS:.1f} ms; glass at 3.5 d*; 48 B/vertex) ==")
    variants = [("size-3 footprint     ", 3, 0.0), ("corner-snap, size 2  ", 2, 1.0)]
    grid = [(512, (1536, 2048, 2560, 3072)), (1024, (2560, 3072, 3584, 4096))]
    fits = {}
    for label, psize, snap in variants:
        for r, ns in grid:
            pts = []
            for n in ns:
                try:
                    (ms,), e = _period_ms(n, r, d, fy, psize, snap)
                except Exception as ex:                    # a stall or timeout is itself a result
                    print(f"  {label} r={r:4d} n={n:5d} ({n * n / 1e6:5.2f} M pts): FAILED {type(ex).__name__}: {ex}")
                    continue
                over = ms > CAP_MS * 1.08
                pts.append((n * n / 1e6, ms, over))
                print(f"  {label} r={r:4d} n={n:5d} ({n * n / 1e6:5.2f} M pts, {n * n / r / r:4.1f} pts/px, "
                      f"{n * n * 48 / 1e6:5.0f} MB): {ms:7.2f} ms/frame  "
                      f"{'' if over else '(at the cap: within budget, cost unknown)'}  errors {e}", flush=True)
            above = [(m, t) for m, t, o in pts if o]
            if len(above) >= 2:
                m = np.array([a[0] for a in above])
                t = np.array([a[1] for a in above])
