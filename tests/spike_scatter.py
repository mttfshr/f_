def structure_score(e, region):
    """Periodic-structure score of a residual image: log10(max / median) of its power spectrum, over the
    region where `region` is True (the rest zeroed), low frequencies excluded. White noise gives about
    log10(20) = 1.3; a lattice moire concentrates power in a few bins and scores several decades higher."""
    x = np.where(region, e - e[region].mean(), 0.0)
    pw = np.abs(np.fft.fft2(x)) ** 2
    h = x.shape[0]
    fy_, fx_ = np.meshgrid(np.fft.fftfreq(h) * h, np.fft.fftfreq(h) * h, indexing="ij")
    ring = np.hypot(fy_, fx_) > 8
    v = pw[ring]
    return float(np.log10(v.max() / max(np.median(v), 1e-30)))


