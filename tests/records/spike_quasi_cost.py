"""spike_quasi_cost.py -- f_quasi T006: cost at 1920x1080 and GPU cos accuracy at large arguments.

Measurement only. The codebox here is a SCRATCH shader generated by this file from the settled model
(.specify/f_quasi/spec.md; mirror tests/modules/quasi/quasi_mirror.py). It is NOT src/f_quasi/codebox_quasi.gen
(T020 writes that, after the gates close). Nothing from here is shipped until it has compiled and read back.

Three legs, in order (each later leg assumes the earlier one passed):
  1. test_variants_compile_and_run    every variant compiles, renders at 64x36 and returns finite values.
  2. test_gpu_cos_accuracy_by_form    the GPU potential P against the float64 mirror at 256x144, for the two
                                      ways of writing the phase (T002 covered float32 arithmetic only; NumPy's
                                      float32 cos is not the GPU's). Forms: "spec" psi = beta s + d 2 pi B s,
                                      "cycles" psi = 2 pi fract(B s d + beta s / 2 pi). The skill measured a 12x
                                      gain from reducing trig arguments on the DFT; this checks whether it matters here.
  3. test_cost_at_1080p               ms per pass at 1920x1080 (benchclient.measure, chain raised until GPU bound):
                                      tex-only, all three outlets (the module as specced), the cycles form,
                                      skipping octaves under a weight threshold, the no-renorm Nyquist fade, both.

Variants (make_code): outputs "tex" (banded look only), "all" (look + vecfield + scalar), "rawP" (accuracy: P raw in
out1); form "spec" | "cycles"; skip (uniform per-octave branch on the weight, `wgt > 0.001`: the weight depends only on
Params, so every pixel takes the same branch); fade (per-octave smoothstep on cycles per pixel, start 0.25, end 0.5,
NOT renormalised: the denominators keep the unfaded weights). Drift is the wrapped base-octave phase in turns of the
T002 finding (offset 2 pi drift 2^i); the accuracy leg runs at drift 0 where it is the mirror's (beta + p) s with p = 0.

Compile hazards avoided (skills/jit-gen-codebox): no unary minus before a product or parenthesis (`0 - ...`, and
negative literals written `(0 - c)`), no variables named e / phi / pi (predefined constants), accumulators declared
before the loop, no `outN` in comments, Params declared before the body and not named like operators.

Needs Max with tests/bench/bench.maxpat open.
Run:  tests/bench.sh tests/records/spike_quasi_cost.py
"""
GROUP = "record"   # a Phase 0 measurement, not a regression gate
ORDER = 91

import math
import sys

import numpy as np

import benchclient as bc
from harness import check, note, run

import quasi_mirror as q

F32, F64 = np.float32, np.float64
BANG = np.zeros((4, 4, 4), np.float32)          # stand-in for the `r draw` bang inlet (first inlet drives the size)
DEFAULTS = dict(zoom=0.3, drift=0.0, density=4.0, envelope=0.5, bands=5.0, angle=0.0, gain=1.0)


def lit(v):
    """A GenExpr literal that never starts with a unary minus."""
    return f"{v:.12f}" if v >= 0 else f"(0 - {abs(v):.12f})"


def make_code(outputs="all", form="spec", skip=False, fade=False):
    betas = q.betas(F64)
    L = ["// scratch cost/accuracy shader generated by tests/records/spike_quasi_cost.py -- NOT the module codebox"]
    for name, d in DEFAULTS.items():
        L.append(f"Param {name}({d});")
    L += [
        "asp = dim.x / dim.y;",
        "px = (norm.x - 0.5) * asp;",
        "py = norm.y - 0.5;",
        "zw = zoom - floor(zoom);",
        "ca = cos(angle);",
        "sa = sin(angle);",
        "twopib = twopi * density;",
    ]
    for k in range(5):
        ck, sk = math.cos(k * math.pi / 5), math.sin(k * math.pi / 5)
        L.append(f"dx{k} = {lit(ck)} * ca - {lit(sk)} * sa;")
        L.append(f"dy{k} = {lit(sk)} * ca + {lit(ck)} * sa;")
    L += ["pacc = 0;", "gxa = 0;", "gya = 0;", "wsum = 0;", "wssum = 0;"]
    L += ["for (i = 0; i < 7; i += 1) {",
          "    ex = zw + i;",
          "    tz = (ex - 3) / envelope;",
          "    wgt = exp(0 - 0.5 * tz * tz);",
          "    sc = exp(ex * 0.6931471805599453);",
          "    pw = exp(i * 0.6931471805599453);",
          "    wsum += wgt;",
          "    wssum += wgt * sc;"]
    if fade:
        L += ["    cpp = density * sc / dim.y;",
              "    wf = wgt * (1 - smoothstep(0.25, 0.5, cpp));"]
    else:
        L += ["    wf = wgt;"]
    body = []
    for k in range(5):
        if form == "spec":
            body.append(f"ps{k} = {lit(betas[k])} * sc + twopi * drift * pw + (dx{k} * px + dy{k} * py) * (twopib * sc);")
        else:
            body.append(f"cy{k} = density * sc * (dx{k} * px + dy{k} * py) + {lit(betas[k] / (2 * math.pi))} * sc + drift * pw;")
            body.append(f"ps{k} = twopi * fract(cy{k});")
    body.append("pacc += wf * (" + " + ".join(f"cos(ps{k})" for k in range(5)) + ");")
    if outputs == "all":
        body.append("gxa += wf * sc * (" + " + ".join(f"sin(ps{k}) * dx{k}" for k in range(5)) + ");")
        body.append("gya += wf * sc * (" + " + ".join(f"sin(ps{k}) * dy{k}" for k in range(5)) + ");")
    if skip:
        L.append("    if (wgt > 0.001) {")
        L += ["        " + b for b in body]
        L.append("    }")
    else:
        L += ["    " + b for b in body]
    L.append("}")
    L.append("pf = pacc / (5 * wsum);")
    if outputs == "rawP":
        L.append("out1 = vec(pf, pf, pf, 1);")
    else:
        L += ["sb = (pf * 0.5 + 1) * bands;",
              "fr = fract(sb);",
              "tri = abs(fr * 2 - 1);",
              "lk = pow(tri, 1.1);"]
        if outputs == "all":
            L += ["vxn = (0 - gxa) / (5 * wssum);",
                  "vyn = (0 - gya) / (5 * wssum);",
                  "vr = clamp(0.5 + 0.5 * gain * vxn, 0, 1);",
                  "vg = clamp(0.5 + 0.5 * gain * vyn, 0, 1);",
                  "sp = pf * 0.5 + 0.5;",
                  "out1 = vec(lk, lk, lk, 1);",
                  "out2 = vec(vr, vg, 0.5, 1);",
                  "out3 = vec(sp, sp, sp, 1);"]
        else:
            L.append("out1 = vec(lk, lk, lk, 1);")
    return "\n".join(L) + "\n"


VARIANTS = [
    ("tex only, spec form, 7 octaves", dict(outputs="tex"), {}),
    ("all outlets, spec form, 7 octaves  [the module as specced]", dict(outputs="all"), {}),
    ("all outlets, cycles form", dict(outputs="all", form="cycles"), {}),
    ("all outlets, skip w<=1e-3 (envelope 0.5)", dict(outputs="all", skip=True), {}),
    ("all outlets, skip w<=1e-3 (envelope 0.7, the cap)", dict(outputs="all", skip=True), {"envelope": 0.7}),
    ("all outlets, no-renorm Nyquist fade", dict(outputs="all", fade=True), {}),
    ("all outlets, skip + fade (envelope 0.7)", dict(outputs="all", skip=True, fade=True), {"envelope": 0.7}),
]


def go(code, dim, params=None, all_outputs=False):
    out, r = bc.run_pass(code, [BANG], dim=dim, params=dict(params or {}), timeout_ms=30000, all_outputs=all_outputs)
    if r["status"] != "ok" or out is None:
        raise AssertionError(f"bench job failed: {r['status']} {r['errors']} ({r['job_dir']})")
    return out


def test_variants_compile_and_run():
    for label, kw, params in VARIANTS + [("raw P, spec form", dict(outputs="rawP"), {}),
                                         ("raw P, cycles form", dict(outputs="rawP", form="cycles"), {})]:
        outs = go(make_code(**kw), (64, 36), params, all_outputs=True)
        first = outs[0]
        assert np.isfinite(first).all(), f"{label}: non-finite output"
        assert float(first[..., :3].std()) > 1e-3, f"{label}: flat output (std {float(first[..., :3].std()):.2e}); check the codebox"
        print(f"    ok   {label}: compiles, finite, std {float(first[..., :3].std()):.3f}")


def test_gpu_cos_accuracy_by_form():
    h, w = 144, 256
    x, y = q.coords(h, w)
    worst = {"spec": 0.0, "cycles": 0.0}
    print("    zoom  dens  env |  max|P_gpu - P_f64|   spec          cycles")
    for env in (0.5, 0.7):
        for dens in (4.0, 12.0):
            for zoom in (0.0, 0.5, 0.999):
                ref = q.field(x.astype(F64), y.astype(F64), zoom=zoom, drift=0.0, density=dens, envelope=env,
                              dtype=F64)["P"]
                row = {}
                for form in ("spec", "cycles"):
                    out = go(make_code(outputs="rawP", form=form), (w, h),
                             dict(zoom=zoom, density=dens, envelope=env))
                    row[form] = float(np.abs(out[..., 0].astype(F64) - ref).max())
                    worst[form] = max(worst[form], row[form])
                print(f"    {zoom:5.3f} {dens:5.1f} {env:4.1f} |                      {row['spec']:.2e}      {row['cycles']:.2e}")
    note("worst GPU error, spec form", f"{worst['spec']:.3e}")
    note("worst GPU error, cycles form", f"{worst['cycles']:.3e}")
    note("float32 NumPy error from T002 for comparison", "2.6e-05; one 8-bit output level of P is 7.8e-03")
    # NF-002 tier-1 tolerance 1e-3; the form T020 should use is the better one
    check("GPU potential error, better of the two forms (NF-002 tolerance)", min(worst.values()), 1e-3)


def cost(code, params, dim=(1920, 1080)):
    r = {}
    for chain in (4, 8, 16, 32):
        r = bc.measure(code, [BANG], dim=dim, chain=chain, params=params)
        if r.get("gpu_bound"):
            return r["ms_per_pass"], chain, True
    return r.get("ms_per_pass_upper_bound", float("nan")), chain, False


def test_cost_at_1080p():
    rows = []
    for label, kw, params in VARIANTS:
        ms, chain, bound = cost(make_code(**kw), params)
        rows.append((label, ms, bound))
        print(f"    ...  {ms:7.3f} ms/pass  {label}  (chain {chain}, {'GPU bound' if bound else 'UPPER BOUND, not resolved'})")
    base = rows[1][1]
    for label, ms, bound in rows:
        if not bound:
            note(f"{label}", "upper bound only: raise the chain or the size before comparing")
    note("module as specced, ms per frame at 1920x1080", f"{base:.3f}")
    note("skipping vs full (envelope 0.5)", f"{rows[3][1] / base:.2f}x of full")
    note("fade vs full", f"{rows[5][1] / base:.2f}x of full")


if __name__ == "__main__":
    sys.exit(run(globals()))
