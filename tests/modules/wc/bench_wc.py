import numpy as np

import benchclient as bc
import wc_mirror as km
from wc_mirror import F32, Params
from harness import check, note, run, slow

SRC = _paths.REPO / "src" / "f_wc"
N = 256
FILES = {"seed": "codebox_seed.gen", "pass": "codebox_pass.gen", "fx": "codebox_dft_fx.gen", "fy": "codebox_dft_fy.gen",
         "spec": "codebox_spec.gen", "iy": "codebox_dft_iy.gen", "ix": "codebox_dft_ix.gen",
         "nl": "codebox_nl.gen", "enc": "codebox_enc.gen"}
BANG = np.zeros((4, 4, 4), np.float32)          # stand-in for the `r draw` bang inlet
# The bench keeps a Param's last value between jobs: every job pins every Param its codebox declares.
PINNED = {"seed": {"salt": 0.0}, "pass": {"reseed": 0.0, "amp": 1.0}, "spec": {"sig_i": 1.4},
          "nl": {"dt": 1.0, "ne": 1.0, "drive_gain": 0.0, "drv_conn": 0.0},
          "enc": {"bypass_gate": 0.0, "sharp": 0.0}}


def code(stage):
    return (SRC / FILES[stage]).read_text()


def gpu(stage, inputs, dim=None, **deltas):
    params = dict(PINNED.get(stage, {}))
    params.update(deltas)
    out, r = bc.run_pass(code(stage), inputs, dim=dim, params=params, timeout_ms=30000)
    if r["status"] != "ok" or out is None:
        raise AssertionError(f"{stage}: bench job failed: {r['status']} {r['errors']} ({r['job_dir']})")
    return out


def white(seed, amp=1.0):
    """A solver-state texture with the mirror's uniform [0, amp) noise in R = E and B = I."""
    return km.seed_state(N, N, seed, amp=F32(amp))


def smooth(seed, amp=1.0, kmax=6):
    """A band-limited random state (low modes in R = E and B = I, scaled to [0, amp]):
    realistic fields, no white noise."""
    rng = np.random.default_rng(seed)
    x = np.arange(N) / N
    s = np.zeros((N, N, 4), F32)
    for c in (0, 2):
        u = np.zeros((N, N))
        for _ in range(12):
            kx, ky = rng.integers(0, kmax, 2)
            u += rng.standard_normal() * np.cos(2 * np.pi * (kx * x[None, :] + ky * x[:, None])
                                                + rng.uniform(0, 6.28))
        s[..., c] = (amp * (u - u.min()) / max(u.max() - u.min(), 1e-9)).astype(F32)
    return s


def gray_drive():
    """The neutral drive texture (mid-0.5, the unconnected neutral)."""
    return km.drive_tex(N, N)


def mx(a, b):
    return float(np.max(np.abs(a - b)))


def rel(a, b):
    return float(np.max(np.abs(a - b)) / max(float(np.max(np.abs(b))), 1e-30))


def g_step(state, nz, driv, dt, ne, dg, sig_i):
    """One solver frame from real GPU passes: fx -> fy -> spec -> iy -> ix -> nl
    (pass is identity here; the host sequences the feedback)."""
    t = gpu("fx", [state])
    t = gpu("fy", [t])
    t = gpu("spec", [t], sig_i=sig_i)
    t = gpu("iy", [t])
    t = gpu("ix", [t])
    return gpu("nl", [t, state, nz, driv], dt=dt, ne=ne, drive_gain=dg, drv_conn=1.0)


def m_step(m, nz, driv, dt, ne, dg, sig_i):
    """The mirror's equivalent frame, fast_fft False = the same per-pixel DFT as the GPU."""
    conv = km.inv_dft_real(km.spec_stage(km.fwd_dft(m, False), sig_i / 1.45, sig_i), False)
    return km.nonlinear_step(conv, m, km.nx_from_hash_tex(nz, dt), driv, dt, ne, dg)


# ----------------------------------------------------------------- compile

def test_every_stage_compiles_and_runs():
    st = smooth(1)
    spectral = km.fwd_dft(st)
    nz = km.hash_noise_tex(N, N, 0.0)
    runs = {
        "seed": lambda: gpu("seed", [BANG], dim=(N, N)),
        "pass": lambda: gpu("pass", [BANG, st, nz], dim=(N, N)),
        "fx": lambda: gpu("fx", [st]), "fy": lambda: gpu("fy", [st]),
        "spec": lambda: gpu("spec", [spectral]),
        "iy": lambda: gpu("iy", [spectral]), "ix": lambda: gpu("ix", [spectral]),
        "nl": lambda: gpu("nl", [st, st, nz, gray_drive()]),
        "enc": lambda: gpu("enc", [BANG, st], dim=(120, 90)),
    }
    for name, fn in runs.items():
        out = fn()
        assert np.isfinite(out).all(), f"{name}: non-finite output"
        print(f"    ok   {name}: compiles, runs, output {out.shape[:2]} finite")


# ----------------------------------------------------------------- seed

def test_seed_noise_statistics():
    a = gpu("seed", [BANG], dim=(N, N))[..., 0].astype(np.float64)
    check("seed R: finite and inside [0, 1)", float(not (np.isfinite(a).all() and a.min() >= 0 and a.max() < 1)), 0.0)
    check("seed R: mean is 0.5 (uniform)", abs(a.mean() - 0.5), 0.01)
    b = gpu("seed", [BANG], dim=(N, N), salt=1.0)
    c = gpu("seed", [BANG], dim=(N, N), salt=1.0)
    check("seed: same salt, same frame", float(np.abs(b - c).max()), 0.0)
    check("seed: a new salt is a new field (uncorrelated)",
          abs(np.corrcoef(a.ravel(), b[..., 0].ravel())[0, 1]), 0.02)
    g = gpu("seed", [BANG], dim=(N, N))
    note("seed R/G correlation (reseed channels must be independent)",
         float(np.corrcoef(g[..., 0].ravel(), g[..., 1].ravel())[0, 1]))
    check("seed: R and G channels uncorrelated",
          abs(np.corrcoef(g[..., 0].ravel(), g[..., 1].ravel())[0, 1]), 0.02)
    check("seed: B and A channels inside [0, 1)",
          float(not (np.isfinite(g).all() and g[..., 2].min() >= 0 and g[..., 2].max() < 1
                     and g[..., 3].min() >= 0 and g[..., 3].max() < 1)), 0.0)


# ----------------------------------------------------------------- DFT chain

def test_dft_chain_matches_np_fft_and_roundtrips():
    """fx -> fy against np.fft.fft2 (float64), BOTH pairs, and the full inverse chain recovers
    the state -- here proving the pair packing (R,G = E-hat; B,A = I-hat) on the shared chain.
    Tolerance per bench_ks: 1e-5 of the spectrum's peak."""
    st = white(2)
    spec = gpu("fy", [gpu("fx", [st])])
    for c, name in ((0, "E"), (2, "I")):
        ref = np.fft.fft2(st[..., c].astype(np.float64))
        err = max(mx(spec[..., c], ref.real), mx(spec[..., c + 1], ref.imag)) / float(np.abs(ref).max())
        check(f"fx -> fy pair {name} vs np.fft.fft2, relative to the spectrum peak", err, 1e-5)
    back = gpu("ix", [gpu("iy", [spec])])
    check("round trip recovers E", mx(back[..., 0], st[..., 0]), 1e-5)
    check("round trip recovers I", mx(back[..., 2], st[..., 2]), 1e-5)
    check("round trip zeroes the imaginary residue (G = A = 0)", float(np.abs(back[..., [1, 3]]).max()), 0.0)


# ----------------------------------------------------------------- pass

def test_pass_reseed_hold_and_heal():
    fb = smooth(3)
    nz = km.hash_noise_tex(N, N, 8.0)                    # what the seed stage hands over (hash)
    seed = km.seed_from_hash(N, N, 8.0)                  # the mirror's reseed result, exactly
    held = gpu("pass", [BANG, fb, nz], dim=(N, N), reseed=0.0)
    check("reseed 0: the feedback state passes through (R AND B)", mx(held, fb), 0.0)
    fresh = gpu("pass", [BANG, fb, nz], dim=(N, N), reseed=1.0)
    check("reseed 1: E from R hash, I from G hash (the mirror's seed_from_hash)", mx(fresh, seed), 2e-7)
    half = gpu("pass", [BANG, fb, nz], dim=(N, N), reseed=1.0, amp=0.5)
    check("reseed 1, amp 0.5: scales the seed", mx(half, seed * 0.5), 2e-7)
    check("reseed 1: imaginary channels stay 0", float(np.abs(fresh[..., [1, 3]]).max()), 0.0)
    poisoned = fb.copy()
    poisoned[10, 10, 0] = np.nan                        # E channel poisoned
    poisoned[10, 10, 2] = np.inf                        # AND the I channel (the heal triggers on BOTH 0)
    cleaned = gpu("pass", [BANG, poisoned, nz], dim=(N, N), reseed=0.0)
    check("reseed 0 over NaN/Inf feedback: no non-finite texel survives",
          float(np.count_nonzero(~np.isfinite(cleaned))), 0.0)
    check("... the both-poisoned texel is healed from the seed channels",
          mx(cleaned[10, 10, [0, 2]], seed[10, 10, [0, 2]]), 2e-7)
    lost = gpu("pass", [BANG, np.zeros((N, N, 4), np.float32), nz], dim=(N, N), reseed=0.0)
    check("SELF-HEAL: a lost (all-zero) state with reseed 0 comes back as the full seed",
          mx(lost, seed), 2e-7)


# ----------------------------------------------------------------- spec

def test_spec_matches_mirror():
    tex = km.fwd_dft(white(5))                          # white noise: Nyquist bins included
    for si in (0.9, 1.4, 3.0):
        got = gpu("spec", [tex], sig_i=si)
        want = km.spec_stage(tex, si / 1.45, si)
        check(f"spec sig_i={si:g}: all four channels match the mirror (rel err)", rel(got, want), 1e-4)
        check(f"spec sig_i={si:g}: the DC bin is NOT zeroed (unchanged)",
              mx(got[0, 0], tex[0, 0]), 0.0)
    peak = float(np.abs(gpu("spec", [tex], sig_i=1.4)).max())
    check("spec: every gain <= 1 (a smoothing kernel, no amplification)",
          float(peak > np.abs(tex).max() + 1e-30), 0.0)


# ----------------------------------------------------------------- nl

def test_nl_matches_mirror_and_contains():
    sig_i = 1.4
    for label, st in (("smooth", smooth(6)), ("white noise", white(7))):
        conv = km.inv_dft_real(km.spec_stage(km.fwd_dft(st), sig_i / 1.45, sig_i))
        nz = km.hash_noise_tex(N, N, 13.0)
        for dt in (0.5, 1.0):
            got = gpu("nl", [conv, st, nz, gray_drive()], dt=dt, ne=1.0, drv_conn=0.0)
            want = km.nonlinear_step(conv, st, km.nx_from_hash_tex(nz, dt), km.drive_tex(N, N), dt, 1.0, 0.0)
            check(f"nl {label} dt={dt:g}: max err vs mirror (R and B)", mx(got, want), 2e-4)
    # drive term connected: the bench wires at most 3 inputs (benchclient run_pass), so in 4 is
    # UNCONNECTED here and reads black (0,0,0,1) -- with drv_conn 1 the codebox then computes the
    # drive term at drv = 0 (dg * -0.5). The mirror is fed the same black drive. The uniform-white
    # scene case is covered live in the module contract bench (real inlet texture).
    st = smooth(7)
    conv = km.inv_dft_real(km.spec_stage(km.fwd_dft(st), sig_i / 1.45, sig_i))
    nz = km.hash_noise_tex(N, N, 14.0)
    black = km.drive_tex(N, N, F32(0.0))
    got = gpu("nl", [conv, st, nz], dt=1.0, ne=1.0, drive_gain=0.8, drv_conn=1.0)
    want = km.nonlinear_step(conv, st, km.nx_from_hash_tex(nz, 1.0), black, 1.0, 1.0, 0.8)
    check("nl drive connected (black inlet = drv 0, dg 0.8): max err vs mirror", mx(got, want), 2e-4)
    moved = gpu("nl", [conv, st, nz, gray_drive()], dt=1.0, ne=1.0, drive_gain=0.8, drv_conn=0.0)
    check("nl drive: drv_conn=0 (unconnected) with dg 0.8 equals drive_gain 0 (the neutral)",
          float(np.abs(moved - gpu("nl", [conv, st, nz, gray_drive()], dt=1.0, ne=1.0)).max()), 2e-4)
    bad = st.copy()
    bad[0, 0, 0] = np.nan
    bad[0, 1, 2] = np.inf
    bad[5, 5, 0] = 1e31
    out = gpu("nl", [conv, bad, nz, gray_drive()], dt=1.0)
    check("nl containment: every texel finite", float(np.count_nonzero(~np.isfinite(out))), 0.0)
    check("nl boundedness: E and I stay inside [0, 1]",
          max(0.0, float(out[..., [0, 2]].max() - 1.0), -float(out[..., [0, 2]].min())), 1e-3)


# ----------------------------------------------------------------- enc

def test_enc_matches_mirror():
    st = smooth(8)
    got = gpu("enc", [BANG, st], dim=(N, N))
    want = km.encode(st, N)
    check("enc 256x256 (1:1): max err vs the mirror's retinotopic encode", mx(got, want), 1e-5)
    for sh in (0.5, 1.0):
        gs = gpu("enc", [BANG, st], dim=(N, N), sharp=sh)
        # the smoothstep crisp curve has slope 18.75 at its midpoint, so the soft error (5e-6)
        # is amplified to ~1e-4 there; the sharp tolerance carries that slope factor
        check(f"enc sharp={sh:g}: max err vs the mirror's encode", mx(gs, km.encode(st, N, sharp=sh)), 1.5e-4)
    for (w, h) in ((120, 90), (400, 300)):
        out = gpu("enc", [BANG, st], dim=(w, h))
        want = km.encode(st, h, sharp=0.0, w=w)
        # the rectangular renders push cu/cv into float32 ranges with ~1e-4-texel ulp
        # (u up to ~8*log(23) ~ 25); the tap error tracks the local gradient at that scale
        check(f"enc {w}x{h}: max err vs the mirror's retinotopic encode", mx(out, want), 1e-4)
        check(f"enc {w}x{h}: G = B = R, A = 1", max(mx(out[..., 1], out[..., 0]), mx(out[..., 2], out[..., 0]),
                                                      mx(out[..., 3], 1.0)), 0.0)
    byp = gpu("enc", [BANG, st], dim=(120, 90), bypass_gate=1.0)
    check("bypass_gate 1: black, A = 1", max(float(np.abs(byp[..., :3]).max()), float(byp[..., 3].min() - 1)), 0.0)
    bad = st.copy()
    bad[20, 20, 0] = np.nan
    bad[21, 21, 0] = np.inf
    out = gpu("enc", [BANG, bad], dim=(N, N))
    check("enc: non-finite state never reaches the outlet", float(np.count_nonzero(~np.isfinite(out))), 0.0)


# ----------------------------------------------------------------- chain

def chain_vs_mirror(frames, marks, sig_i=1.4, dt=1.0, ne=1.0, dg=0.0):
    nz0 = km.hash_noise_tex(N, N, 100.0)
    g = gpu("pass", [BANG, np.zeros((N, N, 4), np.float32), nz0], dim=(N, N), reseed=1.0)
    m = g.copy()                                        # exact same start: the real pass stage seeded it
    driv = gray_drive()
    errs = {}
    t0 = time.time()
    for f in range(1, frames + 1):
        nz = km.hash_noise_tex(N, N, 100.0 + f)         # the GPU seed stage's per-frame stream
        g = g_step(g, nz, driv, dt, ne, dg, sig_i)
        m = m_step(m, nz, driv, dt, ne, dg, sig_i)
        if f in marks:
            errs[f] = mx(g, m)
    print(f"    ...  {frames} frames x 6 jobs in {time.time() - t0:.0f}s (dt {dt:g}, sig_i {sig_i:g})")
    return errs, m, g


def test_chain_30_frames_matches_mirror():
    """30 host-sequenced GPU frames from a real GPU reseed against the mirror (same starting
    texture, same per-frame hash noise stream). WC is driven chaos, so this is a short-horizon
    check: the tolerance covers GPU-vs-float64 Box-Muller rounding and the 4-pass DFT's error
    growth (bench_ks measured ~5e-7 at 30 frames on the same DFT)."""
    errs, m, g = chain_vs_mirror(30, (1, 5, 10, 30))
    for f, e in errs.items():
        note(f"frame {f}: max |GPU - mirror|", e)
    check("30 frames: max |GPU - mirror|", errs[30], 5e-4)
    moved = mx(m, km.seed_from_hash(N, N, 100.0))
    note("how far the state moved from the seed in 30 frames", moved)
    check("the state moved (max change from the seed above 0.02)", float(moved < 0.02), 0.0)
    check("state finite after 30 frames", float(np.count_nonzero(~np.isfinite(g))), 0.0)


@slow       # ~2-3 min: 100 frames x 6 bench jobs, bound by render frames per job, not by the GPU
def test_chain_100_frames_contrast_survives():
    """Past a few hundred frames the values diverge chaotically; the tier-2 long-horizon contract
    is the MECHANISM: the noise-driven pattern's contrast survives on the GPU chain exactly as on
    the mirror (the offline test's std floor), and nothing saturates or dies."""
    errs, m, g = chain_vs_mirror(100, (10, 30, 100))
    for f, e in errs.items():
        note(f"frame {f}: max |GPU - mirror|", e)
    std_g, std_m = float(g[..., 0].std()), float(m[..., 0].std())
    note("frame 100: E contrast GPU / mirror", (std_g, std_m))
    check("100 frames: noise-sustained contrast on the GPU chain", -std_g, -0.03)
    check("100 frames: contrast tracks the mirror (ratio within 3x)",
          max(std_g, std_m) / max(std_g, std_m, 1e-9), 3.0)
    check("100 frames: no saturation death on the GPU chain (std below 0.6)",
          std_g - 0.6, 0.0)


# ----------------------------------------------------------------- cost

def stage_cost(stage, inputs, dim):
    for chain in (8, 16, 32):
        r = bc.measure(code(stage), inputs, dim=dim, chain=chain, params=PINNED.get(stage, {}))
        if r.get("gpu_bound"):
            return r["ms_per_pass"], chain, True
    return r.get("ms_per_pass_upper_bound", float("nan")), chain, False


@slow       # a timing measurement, the noisiest test here; run it when a shader or the bench setup changes
def test_cost_per_stage():
    """T024's measurement: the solver stages at 256^2 (ONE DFT chain carries BOTH fields --
    the f_ks cost class, not 2x), enc at 1280x720. Budget: f_ks measured well under 3 ms;
    wc adds the seed/nl extra inputs and the retinotopic tap, budget 4 ms."""
    st = smooth(9)
    spectral = km.fwd_dft(st)
    nz = km.hash_noise_tex(N, N, 0.0)
    plan = [("seed", [BANG], (N, N)), ("pass", [BANG, st, nz], (N, N)), ("fx", [st], None),
            ("fy", [st], None), ("spec", [spectral], None), ("iy", [spectral], None),
            ("ix", [spectral], None), ("nl", [st, st, nz, gray_drive()], None),
            ("enc", [BANG, st], (1280, 720))]
    total = 0.0
    for stage, inputs, dim in plan:
        ms, chain, bound = stage_cost(stage, inputs, dim)
        total += ms
        print(f"    ...  {stage:5s} {ms:7.3f} ms/pass  (chain {chain}, {'GPU bound' if bound else 'UPPER BOUND, not resolved'})")
    check("sum of stage costs (ms/frame) vs a 4 ms budget", total, 4.0)


