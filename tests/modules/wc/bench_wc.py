"""
bench_wc.py -- f_wc Phase 1 (tasks.md T021, T022, T023, T024): every stage codebox under src/f_wc/
run on the GPU through the codebox bench and diffed against the NumPy mirror in wc_mirror.py, then the
whole chain host-sequenced over many frames (the bench drives one codebox per job; the f_vf_fluid
ADR-10 method, bench_ks.py the template).

Stage jobs (one pass per job, outputs chained from Python):
    pass  in1 = bang stand-in, in2 = feedback state (R = E, B = I), in3 = noise texture (R = seedE, G = seedI)
    seed  in1 = bang stand-in; R/G = reseed hashes, B/A = Box-Muller uniforms (Param salt)
    fx, fy, iy, ix  in1 = previous stage      (f_vf_fluid's DFT, generated by src/f_wc/gen_dft.py)
    spec  in1 = spectral texture (R,G = E-hat, B,A = I-hat), Param sig_i (per-bin kernel gains)
    nl    in1 = convolved (R = cE, B = cI), in2 = raw state, in3 = noise (B,A uniforms), in4 = drive
          (Box-Muller inside, E-only drive; Params dt, ne, drive_gain, drv_conn)
    enc   in1 = bang stand-in, in2 = state; retinotopic 4-tap at RENDER res (Params sharp, bypass_gate)

The per-frame noise stream is REPRODUCIBLE: the host feeds nl the exact hash texture the GPU's seed
stage computes (wc_mirror.hash_noise_tex / nx_from_hash_tex), so the chain test diffs pixels, not
just statistics -- except the GPU's own Box-Muller vs the mirror's float64, covered by the tolerances.

Needs Max with tests/bench/bench.maxpat open.
Run:  tests/bench.sh tests/modules/wc/bench_wc.py
"""
GROUP = "regression"   # tests/bench.sh runs "regression"; see tests/lib/benchdeps.py list --group
