"""
bench_ks.py -- f_ks Phase 1 (tasks.md T007, T020): every stage codebox under src/f_ks/ run on the GPU
through the codebox bench and diffed against the NumPy mirror in ks_mirror.py, then the whole chain
host-sequenced over many frames (the bench drives one codebox per job; the f_vf_fluid ADR-10 method).

Stage jobs (one pass per job, outputs chained from Python):
    pass  in1 = feedback state, in2 = noise texture (R in [0,1])
    fx, fy, iy, ix  in1 = previous stage      (f_vf_fluid's DFT, generated by src/f_ks/gen_dft.py)
    spec  in1 = spectral texture
    nl    in1 = u_lin (the ix output)
    enc   in1 = bang stand-in, in2 = state

Needs Max with tests/bench/bench.maxpat open.
Run:  tests/bench.sh tests/modules/ks/bench_ks.py
"""
GROUP = "regression"   # tests/bench.sh runs "regression"; see tests/lib/benchdeps.py list --group
ORDER = 55

import paths as _paths
import sys
import time

import numpy as np

import benchclient as bc
import ks_mirror as km
from ks_mirror import F32, Params
from harness import check, note, run, slow

SRC = _paths.REPO / "src" / "f_ks"
N = 256
L = 50.0
FILES = {"pass": "codebox_pass.gen", "fx": "codebox_dft_fx.gen", "fy": "codebox_dft_fy.gen",
         "spec": "codebox_spec.gen", "iy": "codebox_dft_iy.gen", "ix": "codebox_dft_ix.gen",
         "nl": "codebox_nl.gen", "enc": "codebox_enc.gen"}
BANG = np.zeros((4, 4, 4), np.float32)          # stand-in for the `r draw` bang inlet
# The bench keeps a Param's last value between jobs: every job pins every Param its codebox declares.
PINNED = {"pass": {"reseed": 0.0, "amp": 1.0}, "spec": {"dt": 0.05, "L": L},
          "nl": {"dt": 0.05, "L": L}, "enc": {"bypass_gate": 0.0}}


def code(stage):
    return (SRC / FILES[stage]).read_text()


def gpu(stage, inputs, dim=None, **deltas):
    params = dict(PINNED.get(stage, {}))
    params.update(deltas)
    out, r = bc.run_pass(code(stage), inputs, dim=dim, params=params, timeout_ms=30000)
    if r["status"] != "ok" or out is None:
        raise AssertionError(f"{stage}: bench job failed: {r['status']} {r['errors']} ({r['job_dir']})")
    return out


def state_from(u):
    """A solver-state texture: R = u, A = 1."""
    s = np.zeros((N, N, 4), F32)
    s[..., 0] = u
    s[..., 3] = 1.0
    return s


def white(seed, amp=1.0):
    return km.seed_state(N, N, seed, amp=amp)


def smooth(seed, amp=1.0, kmax=6):
    """A band-limited random field (a handful of low modes): realistic gradients, no white noise."""
    rng = np.random.default_rng(seed)
    x = np.arange(N) / N
    u = np.zeros((N, N))
    for _ in range(12):
        kx, ky = rng.integers(0, kmax, 2)
        u += rng.standard_normal() * np.cos(2 * np.pi * (kx * x[None, :] + ky * x[:, None]) + rng.uniform(0, 6.28))
    return state_from((amp * u / max(np.abs(u).max(), 1e-9)).astype(F32))


def mx(a, b):
    return float(np.max(np.abs(a - b)))


def rel(a, b):
    return float(np.max(np.abs(a - b)) / max(float(np.max(np.abs(b))), 1e-30))


def g_step(state, dt):
    """One solver frame from real GPU passes: fx -> fy -> spec -> iy -> ix -> nl (pass is identity)."""
    t = gpu("fx", [state])
    t = gpu("fy", [t])
    t = gpu("spec", [t], dt=dt)
    t = gpu("iy", [t])
    t = gpu("ix", [t])
    return gpu("nl", [t], dt=dt)


# ----------------------------------------------------------------- compile

def test_every_stage_compiles_and_runs():
    st = smooth(1)
    spectral = km.fwd_dft(st)
    runs = {
        "pass": lambda: gpu("pass", [st, st]),
        "fx": lambda: gpu("fx", [st]), "fy": lambda: gpu("fy", [st]),
        "spec": lambda: gpu("spec", [spectral]),
        "iy": lambda: gpu("iy", [spectral]), "ix": lambda: gpu("ix", [spectral]),
        "nl": lambda: gpu("nl", [st]),
        "enc": lambda: gpu("enc", [BANG, st], dim=(120, 90)),
    }
    for name, fn in runs.items():
        out = fn()
        assert np.isfinite(out).all(), f"{name}: non-finite output"
        print(f"    ok   {name}: compiles, runs, output {out.shape[:2]} finite")


# ----------------------------------------------------------------- DFT chain

def test_dft_chain_matches_np_fft_and_roundtrips():
    """fx -> fy against np.fft.fft2 (float64), and the full inverse chain recovers the state.
    The codeboxes are f_vf_fluid's (code lines identical, asserted by gen_dft.py); this proves
    them on f_ks's single real field. Tolerance 1e-5 of the spectrum's peak: the twiddle
    reduction mod(k*n, N) keeps the float32 DFT near 7e-7 at N = 256."""
    st = white(2)
    spec = gpu("fy", [gpu("fx", [st])])
    ref = np.fft.fft2(st[..., 0].astype(np.float64))
    err = max(mx(spec[..., 0], ref.real), mx(spec[..., 1], ref.imag)) / float(np.abs(ref).max())
    check("fx -> fy vs np.fft.fft2, relative to the spectrum peak", err, 1e-5)
    back = gpu("ix", [gpu("iy", [spec])])
    check("fx fy iy ix round trip recovers u", mx(back[..., 0], st[..., 0]), 1e-5)
    check("round trip output has R = u only: G = 0", float(np.abs(back[..., 1]).max()), 0.0)


# ----------------------------------------------------------------- pass

def test_pass_reseed_and_hold():
    fb = smooth(3, amp=2.0)
    seed = white(4)                                     # the mirror's own noise, in [-1, 1]
    noise_tex = np.zeros((N, N, 4), F32)
    noise_tex[..., 0] = (seed[..., 0] + 1.0) / 2.0      # what jit.noise would hand over: [0, 1]
    held = gpu("pass", [fb, noise_tex], reseed=0.0)
    check("reseed 0: the feedback state passes through", mx(held[..., 0], fb[..., 0]), 0.0)
    check("reseed 0: A = 1", mx(held[..., 3], 1.0), 0.0)
    fresh = gpu("pass", [fb, noise_tex], reseed=1.0)
    check("reseed 1: (2 noise - 1) equals the mirror's seed_state", mx(fresh[..., 0], seed[..., 0]), 2e-7)
    half = gpu("pass", [fb, noise_tex], reseed=1.0, amp=0.5)
    check("reseed 1, amp 0.5: scales the seed", mx(half[..., 0], 0.5 * seed[..., 0]), 2e-7)
    poisoned = fb.copy()
    poisoned[10, 10, 0] = np.nan
    poisoned[11, 11, 0] = np.inf
    again = gpu("pass", [poisoned, noise_tex], reseed=1.0)
    check("reseed 1 over a NaN/Inf feedback: clean noise, no poison survives",
          mx(again[..., 0], seed[..., 0]), 2e-7)
    cleaned = gpu("pass", [poisoned, noise_tex], reseed=0.0)
    check("reseed 0 over NaN/Inf feedback: non-finite texels become 0, the rest holds",
          float(np.count_nonzero(~np.isfinite(cleaned))), 0.0)
    check("... and the other texels are untouched",
          mx(np.delete(cleaned[..., 0].ravel(), [10 * N + 10, 11 * N + 11]),
             np.delete(poisoned[..., 0].ravel(), [10 * N + 10, 11 * N + 11])), 0.0)
    note("seed is never zero: min |seed| over the field", float(np.abs(fresh[..., 0]).min()))
    check("seed is not the zero field", float(np.abs(fresh[..., 0]).max() > 0.5) - 1.0, 0.0)


# ----------------------------------------------------------------- spec

def test_spec_matches_mirror():
    tex = km.fwd_dft(white(5))                          # white noise: Nyquist bins included
    cases = [(0.0, 50.0), (0.01, 50.0), (0.05, 50.0), (0.0625, 50.0), (0.05, 12.5), (0.1, 50.0)]
    for dt, Lv in cases:
        got = gpu("spec", [tex], dt=dt, L=Lv)
        want = km.spec_stage(tex, dt, Lv)
        check(f"spec dt={dt:g} L={Lv:g}: RG rel err vs mirror", rel(got[..., :2], want[..., :2]), 1e-4)
        check(f"spec dt={dt:g} L={Lv:g}: the k = 0 bin is exactly 0", float(np.abs(got[0, 0, :2]).max()), 0.0)
    g1 = gpu("spec", [tex], dt=0.05, L=50.0)
    check("spec: B and A are 0", float(np.abs(g1[..., 2:]).max()), 0.0)
    # Nyquist neighbours and the table of one decaying and one growing mode, exact per-bin factors
    check("spec at dt 0 is the identity except the DC bin",
          mx(gpu("spec", [tex], dt=0.0)[1:, 1:, :2], tex[1:, 1:, :2]), 1e-6)


# ----------------------------------------------------------------- nl

def test_nl_matches_mirror_and_contains():
    for label, u in (("smooth", smooth(6, amp=3.0)), ("white noise", white(7))):
        for dt in (0.05, 0.0625):
            got = gpu("nl", [u], dt=dt)
            want = km.nonlinear_step(u, dt, dx=L / N)
            check(f"nl {label} dt={dt:g}: max err vs mirror", mx(got[..., 0], want[..., 0]), 1e-4)
    seam = np.zeros((N, N, 4), F32)
    seam[..., 3] = 1.0
    seam[:, 0, 0] = 1.0                                 # a bright column on the x seam
    seam[0, :, 0] += 2.0                                # a bright row on the y seam
    got = gpu("nl", [seam], dt=0.05)
    check("nl periodic seam: matches the mirror's wrap", mx(got[..., 0], km.nonlinear_step(seam, 0.05, dx=L / N)[..., 0]), 1e-5)
    bad = np.zeros((N, N, 4), F32)
    bad[..., 3] = 1.0
    bad[0, 0, 0] = np.nan
    bad[0, 1, 0] = np.inf
    bad[5, 5, 0] = 1e31
    bad[7, 7, 0] = 500.0
    bad[9, 9, 0] = -500.0
    out = gpu("nl", [bad], dt=0.05)
    check("nl containment: every texel finite", float(np.count_nonzero(~np.isfinite(out))), 0.0)
    check("nl containment: every texel within +-100", float(np.abs(out[..., 0]).max() > 100.0 + 1e-3), 0.0)


# ----------------------------------------------------------------- enc

def up_periodic(u, h, w):
    """Independent periodic bilinear upsample of a 256x256 field to h x w (the codebox's 4-tap)."""
    fx = (np.arange(w) + 0.5) / w * N - 0.5
    fy = (np.arange(h) + 0.5) / h * N - 0.5
    x0 = np.floor(fx).astype(int); y0 = np.floor(fy).astype(int)
    tx = (fx - x0)[None, :]; ty = (fy - y0)[:, None]
    xa, xb = x0 % N, (x0 + 1) % N
    ya, yb = y0 % N, (y0 + 1) % N
    u = u.astype(np.float64)
    top = u[np.ix_(ya, xa)] * (1 - tx) + u[np.ix_(ya, xb)] * tx
    bot = u[np.ix_(yb, xa)] * (1 - tx) + u[np.ix_(yb, xb)] * tx
    return top * (1 - ty) + bot * ty


def test_enc_matches_mirror():
    st = smooth(8, amp=3.0)
    got = gpu("enc", [BANG, st], dim=(N, N))
    want = km.encode(st)
    check("enc 256x256 (1:1): max err vs the mirror's encode", mx(got, want), 1e-6)
    for (h, w) in ((90, 120), (60, 100), (300, 400)):
        out = gpu("enc", [BANG, st], dim=(w, h))
        lum = np.clip(0.5 + 0.25 * up_periodic(st[..., 0], h, w), 0.0, 1.0)
        check(f"enc {h}x{w}: R vs periodic bilinear + map", mx(out[..., 0], lum), 2e-6)
        check(f"enc {h}x{w}: G = B = R, A = 1", max(mx(out[..., 1], out[..., 0]), mx(out[..., 2], out[..., 0]),
                                                      mx(out[..., 3], 1.0)), 0.0)
    wide = state_from(np.full((N, N), 40.0, F32))
    check("enc: a large u clamps to 1", mx(gpu("enc", [BANG, wide], dim=(32, 32))[..., 0], 1.0), 0.0)
    byp = gpu("enc", [BANG, st], dim=(120, 90), bypass_gate=1.0)
    check("bypass_gate 1: black, alpha 1 (the f_chladni convention)",
          max(float(np.abs(byp[..., :3]).max()), mx(byp[..., 3], 1.0)), 0.0)
    bad = st.copy()
    bad[20, 20, 0] = np.nan
    bad[21, 21, 0] = np.inf
    out = gpu("enc", [BANG, bad], dim=(N, N))
    check("enc: non-finite state never reaches the outlet", float(np.count_nonzero(~np.isfinite(out))), 0.0)


# ----------------------------------------------------------------- chain

def chain_vs_mirror(frames, rate, marks):
    p = Params(rate=rate)                                # fast_fft False: the same per-pixel DFT as the GPU
    dt = float(km.rate_to_dt(p.rate, p.dt0, p.ceiling))
    seed = white(11)
    noise_tex = np.zeros((N, N, 4), F32)
    noise_tex[..., 0] = (seed[..., 0] + 1.0) / 2.0
    g = gpu("pass", [state_from(0.0), noise_tex], reseed=1.0)     # the real pass stage seeds the run
    m = g.copy()
    errs = {}
    t0 = time.time()
    for f in range(1, frames + 1):
        g = g_step(g, dt)
        m, _ = km.ks_frame(m, p)
        if f in marks:
            errs[f] = mx(g[..., 0], m[..., 0])
    print(f"    ...  {frames} frames x 6 jobs in {time.time() - t0:.0f}s (dt {dt:g})")
    return errs, m, g


def test_chain_30_frames_matches_mirror():
    """30 host-sequenced GPU frames from a real GPU seed against the mirror (same starting texture)."""
    errs, m, g = chain_vs_mirror(30, 1.0, (1, 5, 10, 30))
    for f, e in errs.items():
        note(f"frame {f}: max |GPU - mirror|", e)
    # measured 4.6e-7 (2026-10-21; 1.9e-7 at frame 1, float32 rounding of the 4-pass DFT, then slow growth);
    # 1e-5 is ~20x headroom. KS is chaotic, so this is a short-horizon check: past a few hundred frames
    # compare statistics, not pixels.
    check("30 frames: max |GPU - mirror|", errs[30], 1e-5)
    moved = mx(m[..., 0], white(11)[..., 0])
    note("how far the state moved from the seed in 30 frames (so the test is not vacuous)", moved)
    check("the state moved (max change from the seed above 0.05)", float(moved < 0.05), 0.0)


@slow       # ~60-70 s: 100 frames x 6 bench jobs, bound by render frames per job, not by the GPU
def test_chain_100_frames_matches_mirror():
    errs, m, g = chain_vs_mirror(100, 1.0, (10, 30, 60, 100))
    for f, e in errs.items():
        note(f"frame {f}: max |GPU - mirror|", e)
    # measured 2.3e-6 at frame 100 (0.9e-6 at 60, 0.46e-6 at 30: error roughly doubles per 40 frames, which
    # is the chaotic growth at dt 0.05 over t = 5); 2e-5 is ~9x headroom
    check("100 frames: max |GPU - mirror|", errs[100], 2e-5)
    check("state finite after 100 frames", float(np.count_nonzero(~np.isfinite(g))), 0.0)
    note("GPU mean of u after 100 frames", float(g[..., 0].mean()))
    note("mirror mean of u after 100 frames", float(m[..., 0].mean()))


# ----------------------------------------------------------------- cost

def stage_cost(stage, inputs, dim):
    for chain in (8, 16, 32):
        r = bc.measure(code(stage), inputs, dim=dim, chain=chain, params=PINNED.get(stage, {}))
        if r.get("gpu_bound"):
            return r["ms_per_pass"], chain, True
    return r.get("ms_per_pass_upper_bound", float("nan")), chain, False


@slow       # a timing measurement, the noisiest test here; run it when a shader or the bench setup changes
def test_cost_per_stage():
    """The solver stages at 256^2, enc at 1280x720. The DFT passes alone were 2.08 ms/frame in
    tests/records/spike_ks_dft_cost.py; this adds the small stages."""
    st = smooth(9)
    spectral = km.fwd_dft(st)
    plan = [("pass", [st, st], (N, N)), ("fx", [st], None), ("fy", [st], None), ("spec", [spectral], None),
            ("iy", [spectral], None), ("ix", [spectral], None), ("nl", [st], None),
            ("enc", [BANG, st], (1280, 720))]
    total = 0.0
    for stage, inputs, dim in plan:
        ms, chain, bound = stage_cost(stage, inputs, dim)
        total += ms
        print(f"    ...  {stage:5s} {ms:7.3f} ms/pass  (chain {chain}, {'GPU bound' if bound else 'UPPER BOUND, not resolved'})")
    check("sum of stage costs (ms/frame) vs a 3 ms budget", total, 3.0)


