def g_frame(state, ftex, **real_kw):
    """One solver frame from real GPU passes: pass -> fx -> fy -> spec -> iy -> ix -> real."""
    spec_kw = {k: real_kw.pop(k) for k in ("speed", "damping", "dispersion", "ring") if k in real_kw}
    t = gpu("pass", [BANG, state], dim=(N, N))
    t = gpu("fx", [t])
    t = gpu("fy", [t])
    t = gpu("spec", [t], **spec_kw)
    t = gpu("iy", [t])
    t = gpu("ix", [t])
    return gpu("real", [t, ftex, state], **real_kw)


def chain_vs_mirror(frames, marks, mkw, gkw, strike_frame=1, use_force=True):
    """GPU chain against the mirror from the same empty state. The mirror is the np.fft variant (fast_fft): the
    GPU DFT is within 1e-6 of it per frame (checked above), and 100 pass-chain frames would take minutes."""
    p = mp(fast_fft=True, **mkw)
    ft = force_tex_of(31) if use_force else None
    g = hold_tex(np.zeros((N, N), F32), np.zeros((N, N), F32))
    m = wfm.new_state(N, N)
    phase = 0.0
    errs = {}
    t0 = time.time()
    for f in range(1, frames + 1):
        g = g_frame(g, ft if ft is not None else force_tex_of(31), **gkw)
        m, _, _, phase = wfm.wave_frame(m, p, ft, phase, strike=(f == strike_frame))
        if f in marks:
            # errors relative to each field's own peak: v = d(u)/dt is ~omega times larger than u, so one absolute
            # number would hide u behind v (a pulse has |v| up to ~60 where |u| <= 4)
            errs[f] = max(mx(g[..., 0], m[..., 0]) / max(float(np.abs(m[..., 0]).max()), 1e-3),
                          mx(g[..., 2], m[..., 2]) / max(float(np.abs(m[..., 2]).max()), 1e-3))
    print(f"    ...  {frames} frames x 7 jobs in {time.time() - t0:.0f}s")
    return errs, m, g, phase


