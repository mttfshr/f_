def test_pass_holds_clears_and_strips_the_bookkeeping_channels():
    fb = hold_tex(smooth(3, 2.0), smooth(4, 2.0), strike_counter=7.0, phase=2.5)
    held = gpu("pass", [BANG, fb], dim=(N, N))
    check("reset_gate 0: u passes through", mx(held[..., 0], fb[..., 0]), 0.0)
    check("reset_gate 0: v passes through", mx(held[..., 2], fb[..., 2]), 0.0)
    check("G and A are stripped (the DFT must not see the strike counter or the phase)",
          float(np.abs(held[..., [1, 3]]).max()), 0.0)
    cleared = gpu("pass", [BANG, fb], dim=(N, N), reset_gate=1.0)
    check("reset_gate 1: the whole texture is zero", float(np.abs(cleared).max()), 0.0)
    bad = fb.copy()
    bad[10, 10, 0] = np.nan
    bad[11, 11, 2] = np.inf
    bad[12, 12, 0] = 1e31
    out = gpu("pass", [BANG, bad], dim=(N, N))
    check("non-finite feedback never passes", float(np.count_nonzero(~np.isfinite(out))), 0.0)
    check("... the poisoned texels become 0", float(max(abs(out[10, 10, 0]), abs(out[11, 11, 2]), abs(out[12, 12, 0]))), 0.0)
    check("... the other texels are untouched",
          mx(np.delete(out[..., 0].ravel(), [10 * N + 10, 12 * N + 12]),
             np.delete(fb[..., 0].ravel(), [10 * N + 10, 12 * N + 12])), 0.0)


