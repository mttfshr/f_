def test_dft_chain_carries_two_real_fields():
    """fx -> fy against np.fft.fft2 for BOTH packed fields (u in R,G and v in B,A), and the inverse chain
    returns R = u, B = v. The codeboxes are f_vf_fluid's (code lines asserted identical by gen_dft.py)."""
    rng = np.random.default_rng(21)
    st = packed(rng.standard_normal((N, N)).astype(F32), rng.standard_normal((N, N)).astype(F32))
    spec = gpu("fy", [gpu("fx", [st])])
    ru = np.fft.fft2(st[..., 0].astype(np.float64))
    rv = np.fft.fft2(st[..., 2].astype(np.float64))
    eu = max(mx(spec[..., 0], ru.real), mx(spec[..., 1], ru.imag)) / float(np.abs(ru).max())
    ev = max(mx(spec[..., 2], rv.real), mx(spec[..., 3], rv.imag)) / float(np.abs(rv).max())
    note("forward DFT error vs np.fft, relative to the peak: u / v", f"{eu:.2e} / {ev:.2e}")
    check("fx -> fy: u-hat vs np.fft.fft2", eu, 1e-5)
    check("fx -> fy: v-hat vs np.fft.fft2", ev, 1e-5)
    back = gpu("ix", [gpu("iy", [spec])])
    check("round trip recovers u", mx(back[..., 0], st[..., 0]), 1e-5)
    check("round trip recovers v", mx(back[..., 2], st[..., 2]), 1e-5)
    check("round trip leaves G = A = 0", float(np.abs(back[..., [1, 3]]).max()), 0.0)


