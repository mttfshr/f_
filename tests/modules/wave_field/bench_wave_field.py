def code(stage):
    return (SRC / FILES[stage]).read_text()


def gpu(stage, inputs, dim=None, all_outputs=False, **deltas):
    params = dict(PINNED.get(stage, {}))
    params.update(deltas)
    out, r = bc.run_pass(code(stage), inputs, dim=dim, params=params, timeout_ms=30000, all_outputs=all_outputs)
    if r["status"] != "ok" or out is None:
        raise AssertionError(f"{stage}: bench job failed: {r['status']} {r['errors']} ({r['job_dir']})")
    return out


def mp(**kw):
    """The mirror's Params for the same settings; nu is the codebox's literal 1e-5 (the mirror default)."""
    return wfm.Params(**kw)


def mx(a, b):
    return float(np.max(np.abs(a - b)))


def circ(a, b):
    """Distance between two phases on the circle (they wrap at 2 pi)."""
    return abs((a - b + np.pi) % (2 * np.pi) - np.pi)


def rel(a, b):
    return float(np.max(np.abs(a - b)) / max(float(np.max(np.abs(b))), 1e-30))


def smooth(seed, amp=1.0, kmax=6):
    """A band-limited random field with zero mean (a handful of low modes)."""
    rng = np.random.default_rng(seed)
    x = np.arange(N) / N
    u = np.zeros((N, N))
    for _ in range(12):
        kx, ky = rng.integers(0, kmax, 2)
        u += rng.standard_normal() * np.cos(2 * np.pi * (kx * x[None, :] + ky * x[:, None]) + rng.uniform(0, 6.28))
    u -= u.mean()
    return (amp * u / max(np.abs(u).max(), 1e-9)).astype(F32)


def packed(u, v):
    """The texture the forward DFT reads, and the ix output: R = u, B = v, G = A = 0."""
    t = np.zeros((N, N, 4), F32)
    t[..., 0], t[..., 2] = u, v
    return t


def hold_tex(u, v, strike_counter=0.0, phase=0.0):
    """The hold stage's output: R = u, B = v, G = strike counter, A = 1 + exciter phase."""
    t = packed(u, v)
    t[..., 1] = strike_counter
    t[..., 3] = 1.0 + phase
    return t


def mirror_state(u, v):
    s = wfm.new_state(N, N)
    s[..., 0], s[..., 2] = u, v
    return s


def force_tex_of(seed):
    f = np.zeros((N, N, 4), F32)
    f[..., 0] = 0.5 + 0.5 * smooth(seed)
    f[..., 3] = 1.0
    return f


def regimes(p):
    """How many of the 256x256 bins fall in each damping regime of the mirror's step (under, critical, over)."""
    kx, ky = wfm.signed_k(N, N)
    k = np.sqrt(kx * kx + ky * ky)
    c = F32(p.speed) * F32(p.kref) * np.power(np.maximum(k / F32(p.kref), F32(1e-6)), F32(p.dispersion))
    beta = F32(p.damping) + F32(p.nu) * k * k
    x = ((F32(p.ring) ** 2 + c * c) - beta * beta) * F32(p.dt) ** 2
    return int((x > wfm.TAYLOR_X).sum()), int((np.abs(x) <= wfm.TAYLOR_X).sum()), int((x < -wfm.TAYLOR_X).sum())


