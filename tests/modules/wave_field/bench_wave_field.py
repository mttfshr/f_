def test_real_stage_matches_mirror():
    u, v = smooth(6, 1.0), smooth(7, 1.0)
    lin = packed(u, v)
    ft = force_tex_of(8)
    base = mirror_state(u, v)
    cases = [
        ("neutral (nothing on)", dict(), None, 0.0, False, hold_tex(u, v, 0, 0.0)),
        ("force inlet, src_force 1", dict(force=0.7, src_force=1.0), ft, 0.0, False, hold_tex(u, v, 0, 0.0)),
        ("force ignored when src_force 0", dict(force=0.7, src_force=0.0), None, 0.0, False, hold_tex(u, v, 0, 0.0)),
        ("exciter", dict(amplitude=1.0, frequency=3.0, exc_x=0.3, exc_y=0.6), None, 1.2, False, hold_tex(u, v, 0, 1.2)),
        ("exciter across the seam", dict(amplitude=0.8, exc_x=0.98, exc_y=0.02), None, 0.7, False, hold_tex(u, v, 0, 0.7)),
        ("strike (counter 1 vs hold 0)", dict(strike_id=1.0, exc_x=0.4, exc_y=0.7), None, 0.0, True, hold_tex(u, v, 0, 0.0)),
        ("no repeat (counter 1, hold already 1)", dict(strike_id=1.0), None, 0.0, False, hold_tex(u, v, 1, 0.0)),
        ("sponge edge 1", dict(edge_amt=1.0), None, 0.0, False, hold_tex(u, v, 0, 0.0)),
        ("sponge edge 0.5 + everything", dict(edge_amt=0.5, force=1.0, src_force=1.0, amplitude=0.6, strike_id=3.0,
                                              exc_x=0.1, exc_y=0.9), ft, 2.0, True, hold_tex(u, v, 2, 2.0)),
    ]
    for label, kw, ftex, phase, strike, hold in cases:
        got = gpu("real", [lin, ftex if ftex is not None else force_tex_of(8), hold], **kw)
        p = mp(x=kw.get("exc_x", 0.5), y=kw.get("exc_y", 0.5), edge=kw.get("edge_amt", 0.0),
               frequency=kw.get("frequency", 2.0), force=kw.get("force", 1.0), amplitude=kw.get("amplitude", 0.0))
        # the mirror applies force only through force_tex; src_force 0 means no force inlet
        want = wfm.real_stage(base, p, ftex if kw.get("src_force", 0.0) >= 0.5 else None, phase, strike)
        check(f"real {label}: u vs mirror", mx(got[..., 0], want[..., 0]), 2e-6)
        check(f"real {label}: v vs mirror", mx(got[..., 2], want[..., 2]), 2e-6)
        newphase = (phase + 2 * np.pi * kw.get("frequency", 2.0) * DT) % (2 * np.pi)
        check(f"real {label}: A = 1 + the advanced phase", mx(got[..., 3], 1.0 + newphase), 2e-6)
        check(f"real {label}: G = the strike counter", mx(got[..., 1], float(kw.get("strike_id", 0.0))), 0.0)
    neutral = gpu("real", [lin, force_tex_of(8), hold_tex(u, v, 0, 0.0)])
    check("real neutral: u and v pass through exactly", max(mx(neutral[..., 0], u), mx(neutral[..., 2], v)), 0.0)


def test_strike_counter_is_exactly_once_and_waits_for_reset():
    z = np.zeros((N, N), F32)
    lin = packed(z, z)
    a = gpu("real", [lin, force_tex_of(8), hold_tex(z, z, 0, 0.0)], strike_id=1.0)
    peak = float(a[..., 0].max())
    want_peak = 4.0 * float(np.exp(-(2 * (0.5 / N) ** 2) / 0.0008))      # the four texels around (0.5, 0.5) sit half a texel off
    check("strike fires: the impulse height is 4 (STRIKE_AMP) times the Gaussian at the nearest texel", abs(peak - want_peak), 1e-4)
    check("... G records the counter", mx(a[..., 1], 1.0), 0.0)
    b = gpu("real", [lin, force_tex_of(8), a], strike_id=1.0)
    check("the next frame with the same counter adds nothing", float(np.abs(b[..., 0]).max()), 0.0)
    c = gpu("real", [lin, force_tex_of(8), b], strike_id=2.0)
    check("a new counter strikes again", abs(float(c[..., 0].max()) - want_peak), 1e-4)
    d = gpu("real", [lin, force_tex_of(8), hold_tex(z, z, 1, 0.0)], strike_id=2.0, reset_gate=1.0)
    check("while reset_gate is on the strike waits (u stays 0)", float(np.abs(d[..., 0]).max()), 0.0)
    check("... and G keeps the old counter, so it fires when reset ends", mx(d[..., 1], 1.0), 0.0)
    e = gpu("real", [lin, force_tex_of(8), d], strike_id=2.0, reset_gate=0.0)
    check("reset ends: the waiting strike fires", abs(float(e[..., 0].max()) - want_peak), 1e-4)


def test_real_stage_contains_and_keeps_the_phase_bounded():
    z = np.zeros((N, N), F32)
    bad = packed(z, z)
    bad[0, 0, 0] = np.nan
    bad[0, 1, 0] = np.inf
    bad[5, 5, 0] = 1e31
    bad[7, 7, 0] = 500.0
    bad[9, 9, 2] = -500.0
    out = gpu("real", [bad, force_tex_of(8), hold_tex(z, z, 0, 0.0)])
    check("every texel finite", float(np.count_nonzero(~np.isfinite(out))), 0.0)
    check("u and v within +-100 (U_CAP)", float(np.abs(out[..., [0, 2]]).max() > 100.0 + 1e-3), 0.0)
    ph = hold_tex(z, z, 0, 0.0)
    ph[..., 3] = 1.0 + 6.2
    nxt = gpu("real", [packed(z, z), force_tex_of(8), ph], frequency=4.0)
    a = float(nxt[0, 0, 3]) - 1.0
    check("the phase wraps modulo 2 pi (stays in [0, 2 pi))", float(a < 0 or a >= 2 * np.pi), 0.0)
    junk = hold_tex(z, z, 0, 0.0)
    junk[..., 3] = np.nan
    junk[..., 1] = np.inf
    out2 = gpu("real", [packed(z, z), force_tex_of(8), junk])
    check("a poisoned hold (phase NaN, counter Inf) heals to finite", float(np.count_nonzero(~np.isfinite(out2))), 0.0)


