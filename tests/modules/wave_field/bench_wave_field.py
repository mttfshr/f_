def test_spec_branch_coverage_is_real():
    """The cases below must put bins in all three regimes, or the test proves nothing about FR-003."""
    tot = [0, 0, 0]
    for label, kw in SPEC_CASES.items():
        c = regimes(mp(**kw))
        tot = [a + b for a, b in zip(tot, c)]
        note(f"bins (under / critical / over): {label}", c)
    check("some bins are underdamped", float(tot[0] == 0), 0.0)
    check("some bins sit in the critical (Taylor) band", float(tot[1] == 0), 0.0)
    check("some bins are overdamped", float(tot[2] == 0), 0.0)


def test_spec_matches_mirror_in_every_regime():
    rng = np.random.default_rng(5)
    st = packed(rng.standard_normal((N, N)).astype(F32), rng.standard_normal((N, N)).astype(F32))
